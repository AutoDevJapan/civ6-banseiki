-- Native Heroes & Legends warlords for the absorption PoC. Loaded only in Banseiki.
-- Keep the official framework, but remove the shipped characters from discovery.
CREATE TEMP TABLE JAC_ReplacedHeroes AS
SELECT HeroClassType, UnitType, CreationProjectType FROM HeroClasses
WHERE HeroClassType IN (
  'HEROCLASS_ANANSI','HEROCLASS_ARTHUR','HEROCLASS_BEOWULF','HEROCLASS_HERCULES',
  'HEROCLASS_HIMIKO','HEROCLASS_HIPPOLYTA','HEROCLASS_HUNAHPU','HEROCLASS_OYA',
  'HEROCLASS_MAUI','HEROCLASS_MULAN','HEROCLASS_SINBAD','HEROCLASS_WUKONG');
DELETE FROM HeroClassUnitCommands WHERE HeroClassType IN (SELECT HeroClassType FROM JAC_ReplacedHeroes);
DELETE FROM HeroClassProgressions WHERE HeroClassType IN (SELECT HeroClassType FROM JAC_ReplacedHeroes);
DELETE FROM HeroClasses WHERE HeroClassType IN (SELECT HeroClassType FROM JAC_ReplacedHeroes);
UPDATE Units SET CanTrain = 0 WHERE UnitType IN (SELECT UnitType FROM JAC_ReplacedHeroes);
-- Preserve definitions referenced by official traits, while making their projects unavailable.
UPDATE Projects SET MaxPlayerInstances = 0 WHERE ProjectType IN (SELECT CreationProjectType FROM JAC_ReplacedHeroes);
DELETE FROM ProjectCompletionModifiers WHERE ProjectType IN (SELECT CreationProjectType FROM JAC_ReplacedHeroes);
DROP TABLE JAC_ReplacedHeroes;

