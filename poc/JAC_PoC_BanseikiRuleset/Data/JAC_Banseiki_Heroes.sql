-- The official temple/oracle recall discounts and Gilgamesh's recruitment bonus
-- enumerate vanilla definitions, so bind the same framework effects to the replacements.
CREATE TEMP TABLE JAC_HeroModifierMap AS
SELECT m.ModifierId AS SourceID,
  'JAC_' || suffix.Code || '_' || m.ModifierId AS NewID,
  'UNIT_HERO_JAC_WARLORD_' || suffix.Code AS UnitType,
  'PROJECT_CREATE_HERO_JAC_WARLORD_' || suffix.Code AS ProjectType
FROM Modifiers m CROSS JOIN (SELECT 'A' AS Code UNION ALL SELECT 'B') suffix
WHERE m.ModifierId IN ('MODIFIER_TEMPLE_RECALL_FAITH_COST_DISCOUNT_HERCULES',
  'MODIFIER_ORACLE_RECALL_FAITH_COST_DISCOUNT_HERCULES',
  'MODIFIER_TRAIT_SUMERIA_HEROES_FASTER_CLAIM_HERCULES');
INSERT INTO Modifiers (ModifierId,ModifierType,RunOnce,NewOnly,Permanent,Repeatable,
  OwnerRequirementSetId,SubjectRequirementSetId,OwnerStackLimit,SubjectStackLimit)
SELECT x.NewID,m.ModifierType,m.RunOnce,m.NewOnly,m.Permanent,m.Repeatable,
  m.OwnerRequirementSetId,m.SubjectRequirementSetId,m.OwnerStackLimit,m.SubjectStackLimit
FROM JAC_HeroModifierMap x JOIN Modifiers m ON m.ModifierId=x.SourceID;
INSERT INTO ModifierArguments (ModifierId,Name,Type,Value,Extra,SecondExtra)
SELECT x.NewID,a.Name,a.Type,
  CASE a.Name WHEN 'UnitType' THEN x.UnitType WHEN 'ProjectType' THEN x.ProjectType ELSE a.Value END,
  a.Extra,a.SecondExtra FROM JAC_HeroModifierMap x JOIN ModifierArguments a ON a.ModifierId=x.SourceID;
INSERT INTO BuildingModifiers (BuildingType,ModifierId)
SELECT b.BuildingType,x.NewID FROM JAC_HeroModifierMap x JOIN BuildingModifiers b ON b.ModifierId=x.SourceID;
INSERT INTO TraitModifiers (TraitType,ModifierId)
SELECT t.TraitType,x.NewID FROM JAC_HeroModifierMap x JOIN TraitModifiers t ON t.ModifierId=x.SourceID;
DROP TABLE JAC_HeroModifierMap;

-- The native manager stores per-class vectors: avoid sparse definition IDs after replacement.
CREATE TEMP TABLE JAC_HeroIndices AS SELECT h.HeroClassType,
  (SELECT COUNT(*) FROM HeroClasses p WHERE p.rowid <= h.rowid) AS DenseID FROM HeroClasses h;
UPDATE HeroClasses SET rowid = rowid + (SELECT MAX(rowid) FROM HeroClasses) + 1;
UPDATE HeroClasses SET rowid = (SELECT DenseID FROM JAC_HeroIndices i WHERE i.HeroClassType = HeroClasses.HeroClassType);
DROP TABLE JAC_HeroIndices;
