-- Available routes derive from category access. Only the strongest route and the signature
-- receive STRONG_COST_n. No title or native promotion is used for these nodes.
INSERT INTO JAC_PersonaTreeNodes
SELECT p.LeaderType || '_' || t.TemplateType, p.LeaderType, a.CategoryType,
 r.RouteType, r.Name, r.ExclusiveGroup, t.Depth,
 CASE WHEN t.Depth=1 THEN NULL ELSE p.LeaderType || '_' || r.RouteType || '_' || (t.Depth-1) END,
 (SELECT Value FROM JAC_PersonaTreeParameters WHERE Name=
   (CASE WHEN r.RouteType=p.PreferredRoute THEN 'STRONG_COST_' ELSE 'NODE_COST_' END) || t.Depth),
 t.Name, t.EffectKind, t.Amount, 0, r.SortOrder,
 'JAC_PERSONA_TREE_' || p.LeaderType || '_' || t.TemplateType
FROM JAC_PersonaTreePeople p JOIN JAC_PersonaCategoryAccess a USING (LeaderType)
JOIN JAC_PersonaRouteTemplates r USING (CategoryType) JOIN JAC_PersonaNodeTemplates t USING (RouteType);
INSERT INTO JAC_PersonaTreeNodes
SELECT p.LeaderType || '_SIGNATURE_' || t.Depth, p.LeaderType, p.PreferredCategory,
 'SIGNATURE_' || p.LeaderType, p.SignatureName, NULL, t.Depth,
 CASE WHEN t.Depth=1 THEN NULL ELSE p.LeaderType || '_SIGNATURE_' || (t.Depth-1) END,
 (SELECT Value FROM JAC_PersonaTreeParameters WHERE Name='STRONG_COST_' || t.Depth),
 t.Name, t.EffectKind, t.Amount, 1, 4, 'JAC_PERSONA_TREE_' || p.LeaderType || '_SIGNATURE_' || t.Depth
FROM JAC_PersonaTreePeople p JOIN JAC_PersonaSignatureTemplates t USING (LeaderType);

