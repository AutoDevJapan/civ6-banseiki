//! Reuse CityStates list/quest instances for FULL_CIV small countries too.
pub(super) const LUA: &str = r#"-- Generated by absorption-product-generate (Rust). Do not edit.
include('CityStates_Expansion2')
include('JAC_Absorption_AdmissionUI')
local U=assert(JAC_AbsorptionAdmissionUI)
local extraIM=InstanceManager:new('CityStateRowInstance','CityStateBase',Controls.CityStateStack)
local questIM=InstanceManager:new('QuestInstance','Top',Controls.QuestsStack)
local current=-1
local baseView=ViewCityState
local baseList=ViewList
local baseQuests=GetQuests
local function IsProductMajor(view)
  local p=view and Players[view.From]
  return p and p:IsMajor() and view.Envoys and view.Envoys.Route=='PRODUCT'
end
function JAC_AbsorptionCityStatesAction(from,command)
  if from~=current then return false end
  local view=U.Get(from)
  if not view or view.Status=='UNAVAILABLE' or not Players[view.To]:IsTurnActive() then return false end
  local _,action=U.Action(view)
  if command~=action then
    if command~='SEND_ENVOY' or not view.Envoys or view.Envoys.Route~='PRODUCT'
      or Players[view.To]:GetInfluence():GetTokensToGive()<=0 then return false end
  end
  return U.Send(view,command)
end
local function Capital(actor)
  local player=Players[actor]
  return player and player:GetCities():GetCapitalCity()
end
local function LookAtCountry(actor)
  local city=Capital(actor)
  if not city then return end
  -- Use the base screen's camera placement, without its one-city-only check.
  local width=UIManager:GetScreenSizeVal()
  local offset=width>0 and ((width-Controls.CityStateScroll:GetSizeX())*0.5)/width or 0.33
  if offset<0.1 or offset>0.9 then offset=0.33 end
  UI.LookAtPlotScreenPosition(city:GetX(),city:GetY(),offset,0.5)
end
function GetQuests(player)
  local view=U.Get(player)
  if not view or view.Status=='UNAVAILABLE' then return baseQuests(player) end
  -- Product requirements replace the one-quest/one-token semantics only for
  -- mapped product countries. Unknown ordinary minors keep the official UI.
  return {{Name=U.Text('CONDITIONS'),Description=U.Lines(view),Reward=U.Text('ALL_CONDITIONS'),Callout=''}}
end
local function Actions(view)
  local text,command=U.Action(view)
  Controls.LevyMilitaryButton:SetHide(false)
  Controls.LevyMilitaryButton:SetText(text)
  Controls.LevyMilitaryButton:SetToolTipString(U.Lines(view))
  Controls.LevyMilitaryButton:SetDisabled(not command or not Players[view.To]:IsTurnActive())
  Controls.LevyMilitaryButton:RegisterCallback(Mouse.eLClick,function() if command then JAC_AbsorptionCityStatesAction(view.From,command) end end)
end
function ViewCityState(player)
  current=player
  local view=U.Get(player)
  if not view or view.Status=='UNAVAILABLE' or not IsProductMajor(view) then
    Controls.EnvoysSentButton:RegisterCallback(Mouse.eLClick,OnEnvoySentClick)
    Controls.InfluencedByButton:RegisterCallback(Mouse.eLClick,OnInfluencedByClick)
    Controls.QuestsButton:RegisterCallback(Mouse.eLClick,OnQuestsClick)
    Controls.RelationshipsButton:RegisterCallback(Mouse.eLClick,OnRelationshipsClick)
    baseView(player)
    if view and view.Status~='UNAVAILABLE' then Actions(view) end
    return
  end
  -- A FULL_CIV small country has no official CityStates cache entry. Build
  -- the same existing detail controls directly without faking influence.
  Controls.ListOfCityStates:SetHide(true);Controls.SingleCityState:SetHide(false)
  Controls.CityStateName:SetText(Locale.Lookup(view.Country.Name))
  Controls.CityStateTypeIcon:SetIcon('ICON_'..view.Country.Profile.CivilizationType)
  Controls.TypeValue:SetText(U.Text('SMALL_COUNTRY'));Controls.PatronValue:SetText('')
  Controls.EnvoysSentValue:SetText(tostring(view.Envoys.Envoys))
  Controls.QuestsValue:SetText(tostring(#view.Rows))
  Controls.EnvoysSentArea:SetHide(true);Controls.InfluenceArea:SetHide(true)
  Controls.RelationshipsArea:SetHide(true);Controls.QuestsArea:SetHide(false)
  Controls.QuestsButton:SetSelected(true)
  questIM:ResetInstances()
  local item=questIM:GetInstance()
  item.Title:SetString(U.Text('CONDITIONS'));item.Description:SetString(U.Lines(view))
  item.Reward:SetString(U.Text('REQUIRED_ENVOYS')..' '..view.Envoys.Required);item.Callout:SetString('')
  Controls.QuestsStack:CalculateSize();Controls.QuestsScroll:CalculateSize()
  Controls.ReportArea:DoAutoSize();Controls.SingleViewStack:CalculateSize()
  Actions(view)
  Controls.PeaceWarButton:SetHide(false)
  local canSend=Players[view.To]:GetInfluence():GetTokensToGive()>0 and Players[view.To]:IsTurnActive()
  Controls.PeaceWarButton:SetText(U.Text('SEND_ENVOY'))
  Controls.PeaceWarButton:SetToolTipString(U.Text('SEND_ENVOY_HELP'))
  Controls.PeaceWarButton:SetDisabled(not canSend)
  Controls.PeaceWarButton:RegisterCallback(Mouse.eLClick,function() JAC_AbsorptionCityStatesAction(view.From,'SEND_ENVOY') end)
  -- Existing subsection buttons would ask the base cache for a minor. Keep
  -- them on this country's quest view rather than opening a missing record.
  for _,button in ipairs({Controls.EnvoysSentButton,Controls.InfluencedByButton,Controls.QuestsButton,Controls.RelationshipsButton}) do
    button:RegisterCallback(Mouse.eLClick,function() ViewCityState(player) end)
  end
end
function ViewList()
  current=-1
  baseList();extraIM:ResetInstances()
  local count=0
  for _,view in ipairs(U.SmallCountries()) do if IsProductMajor(view) then
    count=count+1
    local item=extraIM:GetInstance()
    item.NameLabel:SetText(Locale.Lookup(view.Country.Name))
    item.Icon:SetIcon('ICON_'..view.Country.Profile.CivilizationType)
    item.Icon:SetToolTipString(U.Lines(view));item.QuestIcon:SetHide(false)
    item.QuestIcon:SetToolTipString(U.Lines(view))
    item.EnvoyCount:SetText(tostring(view.Envoys.Envoys)..' / '..view.Envoys.Required)
    for _,control in ipairs({item.BonusImage1,item.BonusImage3,item.BonusImage6,item.Suzerain,
      item.BonusImageSuzerainOff,item.BonusImageSuzerainOn,item.SuzerainLabel,item.EnvoyMoreButton,item.EnvoyLessButton}) do control:SetHide(true) end
    for _,button in ipairs({item.Button,item.NameButton}) do
      button:RegisterCallback(Mouse.eLClick,function() ViewCityState(view.From) end)
    end
    item.LookAtButton:SetDisabled(Capital(view.From)==nil)
    item.LookAtButton:RegisterCallback(Mouse.eLClick,function() LookAtCountry(view.From) end)
  end end
  if count>0 then Controls.NoneMet:SetHide(true) end
  Controls.CityStateStack:CalculateSize()
end
-- The same existing entry event can open both official minors and major
-- actors classified as small countries by their geographic reference area.
LuaEvents.CityStates_OpenOverview.Add(function(player)
  local view=U.Get(player)
  if view and view.Status~='UNAVAILABLE' and view.Mode=='SMALL_STATE' then
    OnOpenCityStates();ViewCityState(player)
  end
end)
local function Updated()
  if not ContextPtr:IsHidden() then
    if current>=0 then local view=U.Get(current)
      if view and view.Status~='UNAVAILABLE' then ViewCityState(current) end
    else ViewList() end
  end
end
Events.GameCoreEventPublishComplete.Add(Updated)
"#;
