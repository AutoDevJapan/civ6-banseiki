//! Shared display/command adapter loaded by the two existing screens.
pub(super) const LUA: &str = r#"-- Generated by absorption-product-generate (Rust). Do not edit.
local U={}
-- Shared personality/trait locale lookup.
local function Display(value) return Locale.Lookup(DisplayLocaleKey(value)) end
local function Text(key) return Locale.Lookup('LOC_JAC_ADMISSION_'..key) end
U.Text=Text
function U.Label(row)
  local args={}
  for _,value in ipairs(row.LabelArgs or {}) do args[#args+1]=type(value)=='string' and Locale.Lookup(value) or value end
  return Locale.Lookup(row.Label,unpack(args))
end
local function Api() return ExposedMembers and ExposedMembers.JAC_AbsorptionProduct end
function U.Get(from)
  local api=Api();if not api then return nil end
  return api.Get(from,Game.GetLocalPlayer())
end
function U.SmallCountries()
  local api=Api();return api and api.GetSmallCountries(Game.GetLocalPlayer()) or {}
end
function U.Send(view,command)
  local player=Game.GetLocalPlayer()
  if not view or player<0 or view.To~=player or not Players[player] then return false end
  if command~='CANCEL' and not Players[player]:IsMajor() then return false end
  local params={OnStart='JAC_AbsorptionProduct_Operation',Command=command,From=view.From,
    Nonce=command..':'..view.From..':'..(view.OfferID or 'new')..':'..(view.Envoys and view.Envoys.Envoys or 0),
    OfferID=view.OfferID,ExpectedEnvoys=view.Envoys and view.Envoys.Envoys}
  UI.RequestPlayerOperation(player,PlayerOperations.EXECUTE_SCRIPT,params)
  return true
end
local function Problem(view)
  if not view then return Text('READING') end
  if view.CanCancel then return Text('INTERRUPTED_CANCEL') end
  if view.Status=='UNAVAILABLE' then return Text('UNAVAILABLE') end
  return Text('INTERRUPTED')
end
function U.Lines(view)
  if not view or view.Status=='UNAVAILABLE' then return Problem(view) end
  local lines={Display(view.Country.Name)..' '..Display(view.Country.Profile.PersonalityLabel or view.Country.Profile.Personality)..' / '..Display(view.Country.Profile.TraitLabel or view.Country.Profile.Trait)}
  for _,row in ipairs(view.Rows) do
    local mark=row.Met and '[ICON_Checkmark]' or '[ICON_Bolt]'
    local detail=''
    if row.Kind=='PRODUCT_DEPOSIT' then
      local status=Text(row.Settlement=='CONSUMED' and 'CONSUMED' or row.Settlement=='LEGACY_SETTLED' and 'LEGACY_SETTLED'
        or row.Settlement=='RETURNED' and 'RETURNED' or row.Settlement=='RETURNING' and 'RETURNING'
        or row.Settlement=='COLLECTING' and 'COLLECTING' or row.Met and 'HELD' or 'NOT_PAID')
      detail=' '..Text('GOLD')..' '..tostring(row.Gold)..' / '..Text('FAITH')..' '..tostring(row.Faith)..' ('..status..')'
    elseif row.Current~=nil and row.Minimum~=nil then detail=' '..tostring(row.Current)..' / '..tostring(row.Minimum) end
    if row.Reviewed==false then detail=' '..Text('UNREVIEWED') end
    lines[#lines+1]=mark..' '..U.Label(row)..detail
    for _,relation in ipairs(row.Details or {}) do lines[#lines+1]='  '..U.Label(relation) end
  end
  if view.Envoys then lines[#lines+1]=Text('ENVOYS')..' '..view.Envoys.Envoys..' / '..view.Envoys.Required end
  if (view.Deposit.Gold or 0)>0 or (view.Deposit.Faith or 0)>0 then
    lines[#lines+1]=Text('ESCROW_POLICY')
  end
  if view.Error then lines[#lines+1]=Problem(view) end
  return table.concat(lines,'[NEWLINE]')
end
function U.Action(view)
  if view.CanCancel then return Text('CANCEL'),'CANCEL' end
  if view.Status=='STARTED' then return Text('STARTED'),nil end
  return Text(view.Mode=='SMALL_STATE' and 'REGISTER_SMALL' or 'REGISTER_MERGER'),'REGISTER'
end
JAC_AbsorptionAdmissionUI=U
return U
"#;
