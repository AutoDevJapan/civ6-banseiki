fn effects(oath: &Value) -> Result<Vec<(&str, i64)>> {
    required_array(oath, "effects")?
        .iter()
        .map(|effect| {
            let pair = effect
                .as_array()
                .context("oath effect must be a two-element array")?;
            if pair.len() != 2 {
                bail!("oath effect must be a two-element array");
            }
            Ok((
                pair[0]
                    .as_str()
                    .context("oath effect kind must be a string")?,
                pair[1]
                    .as_i64()
                    .context("oath effect amount must be an integer")?,
            ))
        })
        .collect()
}

