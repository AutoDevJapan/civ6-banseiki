struct SqlRows {
    columns: &'static str,
    values: Vec<Vec<Option<String>>>,
}

#[derive(Default)]
struct SqlBuilder {
    rows: IndexMap<&'static str, SqlRows>,
}

impl SqlBuilder {
    fn add(&mut self, table: &'static str, columns: &'static str, values: Vec<Option<String>>) {
        let rows = self.rows.entry(table).or_insert_with(|| SqlRows {
            columns,
            values: Vec::new(),
        });
        assert_eq!(rows.columns, columns);
        rows.values.push(values);
    }

    fn strings(&mut self, table: &'static str, columns: &'static str, values: &[&str]) {
        self.add(
            table,
            columns,
            values
                .iter()
                .map(|value| Some((*value).to_owned()))
                .collect(),
        );
    }

    fn modifier(&mut self, key: &str, kind: &str, owner: Option<&str>, subject: Option<&str>) {
        self.add(
            "Modifiers",
            "ModifierId, ModifierType, OwnerRequirementSetId, SubjectRequirementSetId",
            vec![
                Some(key.to_owned()),
                Some(kind.to_owned()),
                owner.map(str::to_owned),
                subject.map(str::to_owned),
            ],
        );
    }

    fn argument(&mut self, key: &str, name: &str, value: &str) {
        self.strings(
            "ModifierArguments",
            "ModifierId, Name, Value",
            &[key, name, value],
        );
    }

    fn attach(&mut self, oath: &str, key: &str) {
        self.strings(
            "TraitModifiers",
            "TraitType, ModifierId",
            &["TRAIT_LEADER_MAJOR_CIV", key],
        );
        self.mapping(oath, key);
    }

    fn mapping(&mut self, oath: &str, key: &str) {
        self.strings(
            "JAC_SengokuOathEffects",
            "OathType, ModifierId",
            &[oath, key],
        );
    }

    fn finish(mut self) -> String {
        if let Some(effects) = self.rows.shift_remove("JAC_SengokuOathEffects") {
            self.rows.insert("JAC_SengokuOathEffects", effects);
        }
        let mut out = SQL_HEADER.to_owned();
        for (table, rows) in self.rows {
            out.push_str(&format!(
                "\nINSERT INTO {table} ({}) VALUES\n",
                rows.columns
            ));
            let rendered = rows
                .values
                .into_iter()
                .map(|row| {
                    let values = row
                        .iter()
                        .map(|value| match value {
                            Some(value) => crate::sql_quote(value),
                            None => "NULL".to_owned(),
                        })
                        .collect::<Vec<_>>();
                    format!("  ({})", values.join(", "))
                })
                .collect::<Vec<_>>();
            out.push_str(&rendered.join(",\n"));
            out.push_str(";\n");
        }
        out
    }
}

fn sql_from_catalogue(houses: &[Value]) -> Result<String> {
    let mut rows = SqlBuilder::default();
    for house in houses {
        let house_id = required_string(house, "id")?;
        for (position, oath) in required_array(house, "oaths")?.iter().enumerate() {
            let key = format!("JAC_OATH_{house_id}_{}", required_string(oath, "id")?);
            let tag = format!("LOC_{key}");
            let focus = required_string(oath, "focus")?;
            let quest = required_string(oath, "quest")?;
            quest_labels(quest)?;
            let civ = format!("CIVILIZATION_JAC_{house_id}");
            let position = (position + 1).to_string();
            let name = format!("{tag}_NAME");
            let golden = format!("{tag}_GOLDEN");
            let quest_tag = format!("{tag}_QUEST");
            let icon = format!("ICON_COMMEMORATION_{}", focus_icon(focus)?);
            rows.strings(
                "JAC_SengokuOaths",
                "OathType, CivilizationType, Position, Name, GoldenDescription, QuestDescription, Icon, QuestType, AIFocus",
                &[&key, &civ, &position, &name, &golden, &quest_tag, &icon, quest, focus],
            );
            for age in AGES {
                rows.strings("JAC_SengokuOathAges", "OathType, AgeType", &[&key, age]);
            }
            let requirement = format!("{key}_REQ");
            let gate = format!("{key}_CITY");
            let property = format!("{key}_ON");
            rows.strings(
                "Requirements",
                "RequirementId, RequirementType",
                &[&requirement, "REQUIREMENT_PLOT_PROPERTY_MATCHES"],
            );
            rows.strings(
                "RequirementArguments",
                "RequirementId, Name, Value",
                &[&requirement, "PropertyName", &property],
            );
            rows.strings(
                "RequirementArguments",
                "RequirementId, Name, Value",
                &[&requirement, "PropertyMinimum", "1"],
            );
            rows.strings(
                "RequirementSets",
                "RequirementSetId, RequirementSetType",
                &[&gate, "REQUIREMENTSET_TEST_ALL"],
            );
            rows.strings(
                "RequirementSetRequirements",
                "RequirementSetId, RequirementId",
                &[&gate, &requirement],
            );
            for (index, (kind, amount)) in effects(oath)?.into_iter().enumerate() {
                let mid = format!("{key}_E{}", index + 1);
                let amount = amount.to_string();
                if let Some((yield_type, _)) = yield_info(kind) {
                    rows.modifier(
                        &mid,
                        "MODIFIER_PLAYER_CITIES_ADJUST_CITY_YIELD_MODIFIER",
                        None,
                        Some(&gate),
                    );
                    rows.argument(&mid, "YieldType", yield_type);
                } else {
                    match kind {
                        "military" => rows.modifier(
                            &mid,
                            "MODIFIER_PLAYER_CITIES_ADJUST_MILITARY_UNITS_PRODUCTION",
                            None,
                            Some(&gate),
                        ),
                        "growth" => rows.modifier(
                            &mid,
                            "MODIFIER_PLAYER_CITIES_ADJUST_CITY_GROWTH",
                            None,
                            Some(&gate),
                        ),
                        "walls" => {
                            for (tier, building) in [
                                ("ANCIENT", "BUILDING_WALLS"),
                                ("MEDIEVAL", "BUILDING_CASTLE"),
                                ("RENAISSANCE", "BUILDING_STAR_FORT"),
                            ] {
                                let wall_id = format!("{mid}_{tier}");
                                rows.modifier(
                                    &wall_id,
                                    "MODIFIER_PLAYER_CITIES_ADJUST_BUILDING_PRODUCTION",
                                    None,
                                    Some(&gate),
                                );
                                rows.argument(&wall_id, "BuildingType", building);
                                rows.argument(&wall_id, "Amount", &amount);
                                rows.attach(&key, &wall_id);
                            }
                            continue;
                        }
                        "naval" => {
                            let attach_id = format!("{mid}_ATTACH");
                            rows.modifier(
                                &attach_id,
                                "MODIFIER_PLAYER_CITIES_ATTACH_MODIFIER",
                                None,
                                None,
                            );
                            rows.argument(&attach_id, "ModifierId", &mid);
                            rows.modifier(
                                &mid,
                                "MODIFIER_CITY_ADJUST_UNIT_DOMAIN_PRODUCTION",
                                Some(&gate),
                                None,
                            );
                            rows.argument(&mid, "Domain", "DOMAIN_SEA");
                            rows.attach(&key, &attach_id);
                            rows.mapping(&key, &mid);
                        }
                        _ => bail!("{kind}"),
                    }
                }
                rows.argument(&mid, "Amount", &amount);
                if kind != "naval" {
                    rows.attach(&key, &mid);
                }
            }
        }
    }
    Ok(rows.finish())
}

pub fn sql_text(repo: &Repository) -> Result<String> {
    sql_from_catalogue(&catalogue(repo)?)
}

fn xml_attribute(text: &str) -> String {
    crate::xml_escape(text)
        .replace('"', "&quot;")
        .replace('\t', "&#09;")
        .replace('\n', "&#10;")
        .replace('\r', "&#13;")
}

fn xml_from_catalogue(houses: &[Value]) -> Result<String> {
    let mut texts: IndexMap<String, Vec<String>> = IndexMap::new();
    for (key, values) in UI_TEXT {
        texts.insert(
            format!("LOC_JAC_OATH_{key}"),
            values.into_iter().map(str::to_owned).collect(),
        );
    }
    for house in houses {
        let house_id = required_string(house, "id")?;
        for oath in required_array(house, "oaths")? {
            let key = format!("LOC_JAC_OATH_{house_id}_{}", required_string(oath, "id")?);
            let names = required_array(oath, "names")?
                .iter()
                .map(|name| {
                    name.as_str()
                        .map(str::to_owned)
                        .context("oath name must be a string")
                })
                .collect::<Result<Vec<_>>>()?;
            texts.insert(format!("{key}_NAME"), names);
            texts.insert(
                format!("{key}_GOLDEN"),
                (0..3)
                    .map(|lang| effect_text(oath, lang))
                    .collect::<Result<_>>()?,
            );
            texts.insert(
                format!("{key}_QUEST"),
                (0..3)
                    .map(|lang| quest_text(oath, lang))
                    .collect::<Result<_>>()?,
            );
        }
    }
    let mut out = String::from(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<GameData>\n\t<!-- Generated by tools/generate_sengoku_oaths.py. -->\n\t<LocalizedText>\n",
    );
    for (key, values) in texts {
        for (language, text) in LANGUAGES.into_iter().zip(values) {
            out.push_str(&format!(
                "\t\t<Row Tag=\"{}\" Language=\"{language}\">\n",
                xml_attribute(&key)
            ));
            if text.is_empty() {
                out.push_str("\t\t\t<Text />\n");
            } else {
                out.push_str(&format!(
                    "\t\t\t<Text>{}</Text>\n",
                    crate::xml_escape(&text)
                ));
            }
            out.push_str("\t\t</Row>\n");
        }
    }
    out.push_str("\t</LocalizedText>\n</GameData>\n");
    Ok(out)
}

pub fn text_xml(repo: &Repository) -> Result<String> {
    xml_from_catalogue(&catalogue(repo)?)
}

pub fn outputs(repo: &Repository) -> Result<Outputs> {
    let houses = catalogue(repo)?;
    Ok([
        (PathBuf::from(SQL_PATH), sql_from_catalogue(&houses)?),
        (PathBuf::from(TEXT_PATH), xml_from_catalogue(&houses)?),
    ]
    .into_iter()
    .collect())
}

pub fn cli(repo: &Repository, args: &[String]) -> Result<()> {
    let Some(check) = crate::parse_check_args(
        "generate-sengoku-oaths",
        args,
        "Generate oath data and ja/en/ru text. Use --check to verify the generated files.",
    )?
    else {
        return Ok(());
    };
    let generated = outputs(repo)?;
    if check {
        for relative in [SQL_PATH, TEXT_PATH] {
            let path = PathBuf::from(relative);
            let expected = generated.get(&path).context("missing oath output")?;
            if !repo.path(&path).is_file() || repo.read(&path)? != *expected {
                bail!("Stale oath artifact: {}\n", path.display());
            }
        }
    } else {
        crate::apply_outputs(repo, generated, false)?;
    }
    println!(
        "oaths: 22 houses, 66 choices; {}",
        if check { "up to date" } else { "generated" }
    );
    Ok(())
}

