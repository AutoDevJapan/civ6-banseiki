    fn query(db: &Connection, sql: &str, args: &[&str]) -> Result<Vec<Vec<Value>>> {
        let mut statement = db.prepare(sql)?;
        let columns = statement.column_count();
        let rows = statement.query_map(params_from_iter(args.iter()), |row| {
            (0..columns)
                .map(|column| {
                    Ok(match row.get::<_, SqlValue>(column)? {
                        SqlValue::Null => Value::Null,
                        SqlValue::Integer(n) => json!(n),
                        SqlValue::Real(n) => json!(n),
                        SqlValue::Text(text) => json!(text),
                        SqlValue::Blob(bytes) => json!(bytes),
                    })
                })
                .collect::<rusqlite::Result<Vec<_>>>()
        })?;
        Ok(rows.collect::<rusqlite::Result<Vec<_>>>()?)
    }

    fn q(db: &Connection, sql: &str) -> Vec<Vec<Value>> {
        query(db, sql, &[]).unwrap()
    }

    fn scalar(db: &Connection, sql: &str, args: &[&str]) -> Value {
        let rows = query(db, sql, args).unwrap();
        assert_eq!(rows.len(), 1, "{sql}: {args:?}");
        assert_eq!(rows[0].len(), 1);
        rows[0][0].clone()
    }

    fn strings(rows: Vec<Vec<Value>>, column: usize) -> BTreeSet<String> {
        rows.into_iter()
            .map(|row| row[column].as_str().unwrap().to_owned())
            .collect()
    }

    fn register_hash(db: &Connection) -> Result<()> {
        crate::cascade::register_audit_hash(db)
    }

    fn xml_value(text: &str) -> SqlValue {
        if text.eq_ignore_ascii_case("true") {
            SqlValue::Integer(1)
        } else if text.eq_ignore_ascii_case("false") {
            SqlValue::Integer(0)
        } else {
            SqlValue::Text(text.to_owned())
        }
    }

    fn xml_fields(node: Node<'_, '_>) -> IndexMap<String, SqlValue> {
        let mut fields = IndexMap::new();
        for attribute in node.attributes() {
            fields.insert(attribute.name().to_owned(), xml_value(attribute.value()));
        }
        for child in node.children().filter(Node::is_element) {
            fields.insert(
                child.tag_name().name().to_owned(),
                xml_value(child.text().unwrap_or("")),
            );
        }
        fields
    }

    fn where_clause(fields: &IndexMap<String, SqlValue>) -> String {
        if fields.is_empty() {
            "1".to_owned()
        } else {
            fields
                .keys()
                .map(|key| format!("{}=?", identifiers(key)))
                .collect::<Vec<_>>()
                .join(" AND ")
        }
    }

    fn child<'a, 'input>(node: Node<'a, 'input>, name: &str) -> Result<Node<'a, 'input>> {
        node.children()
            .find(|child| child.is_element() && child.tag_name().name() == name)
            .with_context(|| format!("missing XML element {name}"))
    }

    fn load_xml(db: &Connection, source: &str, tables: &BTreeSet<String>) -> Result<()> {
        let document = Document::parse(source)?;
        for table in document.root_element().children().filter(Node::is_element) {
            let name = table.tag_name().name();
            if !tables.contains(name) {
                continue;
            }
            for op in table.children().filter(Node::is_element) {
                match op.tag_name().name() {
                    "Row" | "Replace" => {
                        let fields = xml_fields(op);
                        let columns = fields
                            .keys()
                            .map(|key| identifiers(key))
                            .collect::<Vec<_>>();
                        let placeholders = vec!["?"; fields.len()].join(",");
                        let verb = if op.tag_name().name() == "Replace" {
                            "INSERT OR REPLACE"
                        } else {
                            "INSERT OR IGNORE"
                        };
                        db.execute(
                            &format!(
                                "{verb} INTO {} ({}) VALUES ({placeholders})",
                                identifiers(name),
                                columns.join(",")
                            ),
                            params_from_iter(fields.values()),
                        )?;
                    }
                    "Update" => {
                        let conditions = xml_fields(child(op, "Where")?);
                        let sets = xml_fields(child(op, "Set")?);
                        let assignments = sets
                            .keys()
                            .map(|key| format!("{}=?", identifiers(key)))
                            .collect::<Vec<_>>()
                            .join(",");
                        db.execute(
                            &format!(
                                "UPDATE {} SET {assignments} WHERE {}",
                                identifiers(name),
                                where_clause(&conditions)
                            ),
                            params_from_iter(sets.values().chain(conditions.values())),
                        )?;
                    }
                    "Delete" => {
                        let conditions = xml_fields(op);
                        db.execute_batch("PRAGMA foreign_keys=ON")?;
                        db.execute(
                            &format!(
                                "DELETE FROM {} WHERE {}",
                                identifiers(name),
                                where_clause(&conditions)
                            ),
                            params_from_iter(conditions.values()),
                        )?;
                        db.execute_batch("PRAGMA foreign_keys=OFF")?;
                    }
                    _ => {}
                }
            }
        }
        Ok(())
    }

    fn official_db(repo: &Repository) -> Result<Connection> {
        let db = Connection::open_in_memory()?;
        db.execute_batch("PRAGMA foreign_keys=OFF")?;
        register_hash(&db)?;
        for path in [
            "Base/Assets/Gameplay/Data/Schema/01_GameplaySchema.sql",
            "Base/Assets/Gameplay/Data/Schema/02_AddTriggers.sql",
        ] {
            db.execute_batch(&repo.game_read(path)?)
                .with_context(|| format!("official schema {path}"))?;
        }
        let meta_source = repo.game_read("DLC/Expansion2/Expansion2.modinfo")?;
        let meta = Document::parse(&meta_source)?;
        let actions = child(meta.root_element(), "InGameActions")?;
        let mut expansion = Vec::new();
        for component in [
            "Expansion2Core",
            "Expansion2CoreContent",
            "Expansion2MajorContent",
        ] {
            let action = actions
                .children()
                .find(|node| {
                    node.is_element()
                        && node.tag_name().name() == "UpdateDatabase"
                        && node.attribute("id") == Some(component)
                })
                .with_context(|| format!("missing official component {component}"))?;
            let mut files = action
                .children()
                .filter(|node| node.is_element() && node.tag_name().name() == "File")
                .map(|node| {
                    Ok((
                        node.attribute("Priority").unwrap_or("0").parse::<i64>()?,
                        PathBuf::from("DLC/Expansion2")
                            .join(node.text().context("official File without a path")?),
                    ))
                })
                .collect::<Result<Vec<_>>>()?;
            files.sort_by_key(|(priority, _)| std::cmp::Reverse(*priority));
            expansion.extend(files.into_iter().map(|(_, path)| path));
        }
        let first = expansion
            .first()
            .context("official expansion has no data files")?;
        db.execute_batch(&repo.game_read(first)?)?;
        let tables = strings(
            q(&db, "SELECT name FROM sqlite_master WHERE type='table'"),
            0,
        );
        let base = PathBuf::from("Base/Assets/Gameplay/Data");
        let mut files = std::fs::read_dir(repo.game_path(&base))?
            .map(|entry| {
                let entry = entry?;
                Ok(base.join(entry.file_name()))
            })
            .collect::<std::io::Result<Vec<_>>>()?;
        files.retain(|path| path.extension().and_then(|ext| ext.to_str()) == Some("xml"));
        files.sort();
        assert!(!files.is_empty(), "official base XML files are required");
        for path in files {
            load_xml(&db, &repo.game_read(&path)?, &tables)
                .with_context(|| format!("official XML {}", path.display()))?;
        }
        for path in expansion.iter().skip(1) {
            load_xml(&db, &repo.game_read(path)?, &tables)
                .with_context(|| format!("official expansion XML {}", path.display()))?;
        }
        Ok(db)
    }

    fn sengoku_db(repo: &Repository, original: &Connection) -> Result<Connection> {
        let mut db = Connection::open_in_memory()?;
        {
            let backup = Backup::new(original, &mut db)?;
            backup.run_to_completion(100, Duration::from_millis(1), None)?;
        }
        register_hash(&db)?;
        db.execute_batch("PRAGMA foreign_keys=ON")?;
        let meta_source = repo.read(format!("{MOD}/JAC_PoC_SengokuTrees.modinfo"))?;
        let meta = Document::parse(&meta_source)?;
        let actions = child(meta.root_element(), "InGameActions")?;
        let generated = outputs(repo)?;
        for action in actions.children().filter(Node::is_element) {
            if action.tag_name().name() != "UpdateDatabase" {
                continue;
            }
            for file in action.children().filter(Node::is_element) {
                if file.tag_name().name() != "File" {
                    continue;
                }
                let name = file.text().context("Sengoku File without a path")?;
                if !name.ends_with(".sql") {
                    continue;
                }
                let relative = PathBuf::from(MOD).join(name);
                let script = match generated.get(&relative) {
                    Some(script) => script.clone(),
                    None => repo.read(&relative)?,
                };
                db.execute_batch(&format!(
                    "BEGIN; PRAGMA defer_foreign_keys=ON;\n{script}\nCOMMIT;"
                ))
                .with_context(|| format!("Sengoku SQL {name}"))?;
            }
        }
        Ok(db)
    }

