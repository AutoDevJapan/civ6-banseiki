fn required_string<'a>(value: &'a Value, key: &str) -> Result<&'a str> {
    value
        .get(key)
        .and_then(Value::as_str)
        .with_context(|| format!("oath catalogue: {key} must be a string"))
}

fn required_array<'a>(value: &'a Value, key: &str) -> Result<&'a Vec<Value>> {
    value
        .get(key)
        .and_then(Value::as_array)
        .with_context(|| format!("oath catalogue: {key} must be an array"))
}

pub fn catalogue(repo: &Repository) -> Result<Vec<Value>> {
    let source = repo.json(SOURCE)?;
    Ok(required_array(&source, "houses")?.clone())
}

