    fn year_after(curves: &SpeedStages, speed: &str, elapsed_turns: i64) -> i64 {
        let mut months = 0;
        let mut remaining = elapsed_turns;
        for &(increment, turns) in &curves[speed] {
            let used = remaining.min(turns);
            months += used * increment;
            remaining -= used;
            if remaining == 0 {
                break;
            }
        }
        assert_eq!(remaining, 0, "{speed}");
        1534 + months.div_euclid(12)
    }

