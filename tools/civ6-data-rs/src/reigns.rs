fn string<'a>(value: &'a Value, key: &str) -> Result<&'a str> {
    value
        .get(key)
        .and_then(Value::as_str)
        .ok_or_else(|| anyhow!("expected string field {key}: {value}"))
}

fn integer(value: &Value, key: &str) -> Result<i64> {
    value
        .get(key)
        .and_then(Value::as_i64)
        .ok_or_else(|| anyhow!("expected integer field {key}: {value}"))
}

fn reign_list(data: &Value) -> Result<&[Value]> {
    data.get("reigns")
        .and_then(Value::as_array)
        .map(Vec::as_slice)
        .ok_or_else(|| anyhow!("expected reigns array"))
}

fn start_reign(data: &Value) -> Result<&Value> {
    data.get("start")
        .filter(|value| value.is_object())
        .ok_or_else(|| anyhow!("expected start reign object"))
}

fn multiplier(speed: &str) -> Result<i64> {
    match speed {
        "GAMESPEED_ONLINE" => Ok(50),
        "GAMESPEED_QUICK" => Ok(67),
        "GAMESPEED_STANDARD" => Ok(100),
        "GAMESPEED_EPIC" => Ok(150),
        "GAMESPEED_MARATHON" => Ok(300),
        _ => bail!("unknown game speed: {speed}"),
    }
}

pub fn load(repo: &Repository) -> Result<Value> {
    repo.json(REIGNS_JSON)
}

fn reign_months_from(data: &Value) -> Result<Vec<i64>> {
    reign_list(data)?
        .iter()
        .map(|reign| Ok((integer(reign, "year")? - START_YEAR) * 12 + integer(reign, "month")? - 1))
        .collect()
}

pub fn reign_months(repo: &Repository) -> Result<Vec<i64>> {
    reign_months_from(&load(repo)?)
}

/// Return the game-relative turn whose dates contain the requested month.
/// Stages are traversed in their stored order, including the final boundary.
pub fn turn_containing(month: i64, stages: &[Stage]) -> i64 {
    let mut months = 0;
    let mut turn = 1;
    for &(increment, turns) in stages {
        let span = turns * increment;
        if month < months + span {
            return turn + (month - months).div_euclid(increment);
        }
        months += span;
        turn += turns;
    }
    turn
}

fn eras_from(data: &Value) -> Result<Vec<Value>> {
    let reigns = reign_list(data)?;
    let start = start_reign(data)?;
    let months = reign_months_from(data)?;
    let mut starts = Vec::with_capacity(months.len() + 1);
    starts.push(1);
    starts.extend(
        months
            .iter()
            .map(|&month| turn_containing(month, &STANDARD_STAGES)),
    );

    let mut result = Vec::with_capacity(reigns.len() + 1);
    for (index, reign) in std::iter::once(start).chain(reigns.iter()).enumerate() {
        let id = string(reign, "id")?;
        let length = starts.get(index + 1).map(|&next| next - starts[index]);
        if let Some(length) = length {
            if length < MIN_ERA_TURNS {
                bail!("{id} lasts {length} standard turns; an era lasts at least {MIN_ERA_TURNS}");
            }
        }
        let era_type = OFFICIAL_ERAS
            .get(index)
            .map(|&era| era.to_owned())
            .unwrap_or_else(|| format!("ERA_JAC_{id}"));
        result.push(json!({
            "EraType": era_type,
            "id": id,
            "ChronologyIndex": index + 1,
            "length": length,
        }));
    }
    Ok(result)
}

pub fn eras(repo: &Repository) -> Result<Vec<Value>> {
    eras_from(&load(repo)?)
}

fn engine_turns_from(all_eras: &[Value], speed: &str) -> Result<Vec<i64>> {
    let factor = multiplier(speed)?;
    let mut turn = 1;
    let mut result = Vec::with_capacity(all_eras.len().saturating_sub(1));
    for era in all_eras.iter().take(all_eras.len().saturating_sub(1)) {
        let length = integer(era, "length")?;
        turn += MIN_ERA_TURNS.max((length * factor).div_euclid(100));
        result.push(turn);
    }
    Ok(result)
}

pub fn engine_turns(repo: &Repository, speed: &str) -> Result<Vec<i64>> {
    engine_turns_from(&eras(repo)?, speed)
}

fn era_of_date_from(data: &Value, all_eras: &[Value], year: i64, month: i64) -> Result<String> {
    let first = all_eras.first().ok_or_else(|| anyhow!("no engine eras"))?;
    let mut current = string(first, "EraType")?;
    for (era, reign) in all_eras.iter().skip(1).zip(reign_list(data)?) {
        if (integer(reign, "year")?, integer(reign, "month")?) <= (year, month) {
            current = string(era, "EraType")?;
        }
    }
    Ok(current.to_owned())
}

pub fn era_of_date(repo: &Repository, year: i64, month: i64) -> Result<String> {
    let data = load(repo)?;
    let all_eras = eras_from(&data)?;
    era_of_date_from(&data, &all_eras, year, month)
}

/// CPython's Random(0): MT19937 initialized with init_by_array([0]).
/// Each random() consumes two tempered words and returns a 53-bit fraction.
struct PythonRandom {
    state: [u32; 624],
    index: usize,
}

impl PythonRandom {
    fn seed_zero() -> Self {
        let mut rng = Self {
            state: [0; 624],
            index: 624,
        };
        rng.state[0] = 19650218;
        for i in 1..624 {
            rng.state[i] = 1812433253_u32
                .wrapping_mul(rng.state[i - 1] ^ (rng.state[i - 1] >> 30))
                .wrapping_add(i as u32);
        }

        let mut i = 1;
        for _ in 0..624 {
            let mixed = (rng.state[i - 1] ^ (rng.state[i - 1] >> 30)).wrapping_mul(1664525);
            // The sole key word and its index are both zero.
            rng.state[i] ^= mixed;
            i += 1;
            if i >= 624 {
                rng.state[0] = rng.state[623];
                i = 1;
            }
        }
        for _ in 0..623 {
            let mixed = (rng.state[i - 1] ^ (rng.state[i - 1] >> 30)).wrapping_mul(1566083941);
            rng.state[i] = (rng.state[i] ^ mixed).wrapping_sub(i as u32);
            i += 1;
            if i >= 624 {
                rng.state[0] = rng.state[623];
                i = 1;
            }
        }
        rng.state[0] = 0x80000000;
        rng
    }

    fn next_u32(&mut self) -> u32 {
        if self.index >= 624 {
            // In-place traversal is intentional: it matches CPython's twist.
            for i in 0..624 {
                let y = (self.state[i] & 0x80000000) | (self.state[(i + 1) % 624] & 0x7fffffff);
                self.state[i] = self.state[(i + 397) % 624]
                    ^ (y >> 1)
                    ^ if y & 1 != 0 { 0x9908b0df } else { 0 };
            }
            self.index = 0;
        }
        let mut y = self.state[self.index];
        self.index += 1;
        y ^= y >> 11;
        y ^= (y << 7) & 0x9d2c5680;
        y ^= (y << 15) & 0xefc60000;
        y ^= y >> 18;
        y
    }

    fn random(&mut self) -> f64 {
        let a = (self.next_u32() >> 5) as f64;
        let b = (self.next_u32() >> 6) as f64;
        (a * 67108864.0 + b) * (1.0 / 9007199254740992.0)
    }
}

fn python_round(value: f64) -> i64 {
    value.round_ties_even() as i64
}

fn rounded_ratio(numerator: i64, denominator: i64) -> i64 {
    python_round(numerator as f64 / denominator as f64)
}

fn chunked(turns: i64, months: i64, chunks: i64, high_first: bool) -> Option<Vec<Stage>> {
    let cuts: Vec<i64> = (0..=chunks)
        .map(|i| rounded_ratio(turns * i, chunks))
        .collect();
    let mut runs: Vec<Stage> = Vec::new();
    let mut high = high_first;
    for pair in cuts.windows(2) {
        let start = pair[0];
        let end = pair[1];
        let span = rounded_ratio(months * end, turns) - rounded_ratio(months * start, turns);
        let count = end - start;
        let low = span.div_euclid(count);
        let extra = span.rem_euclid(count);
        if low < 1 {
            return None;
        }
        let part = if high {
            [(low + 1, extra), (low, count - extra)]
        } else {
            [(low, count - extra), (low + 1, extra)]
        };
        for run in part {
            if run.1 == 0 {
                continue;
            }
            if let Some(last) = runs.last_mut() {
                if last.0 == run.0 {
                    last.1 += run.1;
                    continue;
                }
            }
            runs.push(run);
        }
        high = !high;
    }
    Some(runs)
}

fn gap(runs: &[Stage], turns: i64, months: i64) -> f64 {
    let mut total = 0;
    let mut turn = 0;
    let mut worst: f64 = 0.0;
    for &(increment, count) in runs {
        for _ in 0..count {
            total += increment;
            turn += 1;
            worst = worst.max((total as f64 - (months * turn) as f64 / turns as f64).abs());
        }
    }
    worst
}

fn span_options(turns: i64, months: i64, first_above: i64) -> Vec<(Vec<Stage>, f64)> {
    let pace = months as f64 / turns as f64;
    // Python dict preserves the position of overwritten keys. Stable sorting
    // then preserves insertion order for equally even options.
    let mut out: IndexMap<Vec<Stage>, f64> = IndexMap::new();
    if months.rem_euclid(turns) == 0 && months.div_euclid(turns) > first_above {
        out.insert(vec![(months.div_euclid(turns), turns)], 0.0);
    }
    for first in (first_above + 1)..(pace as i64 + 4) {
        for count in 1..turns {
            let remaining = months - first * count;
            let later = remaining.div_euclid(turns - count);
            let remainder = remaining.rem_euclid(turns - count);
            if remainder == 0 && later >= 1 && later != first && (later as f64 - pace).abs() < 4.0 {
                out.insert(
                    vec![(first, count), (later, turns - count)],
                    (first as f64 - pace).abs() * count as f64,
                );
            }
        }
    }
    for chunks in 2..=2.max(turns / 8) {
        for high_first in [true, false] {
            if let Some(runs) = chunked(turns, months, chunks, high_first) {
                if runs.first().is_some_and(|run| run.0 > first_above) {
                    let unevenness = gap(&runs, turns, months);
                    out.entry(runs).or_insert(unevenness);
                }
            }
        }
    }
    let mut result: Vec<_> = out
        .into_iter()
        .filter(|(runs, _)| runs.iter().map(|run| run.0).max().is_some_and(|m| m <= 12))
        .collect();
    result.sort_by(|left, right| left.1.total_cmp(&right.1));
    result
}

fn rows_for(run: Stage, used: &BTreeSet<Stage>) -> Option<Vec<Stage>> {
    if !used.contains(&run) {
        return Some(vec![run]);
    }
    let (increment, count) = run;
    for part in (1..=count / 2).rev() {
        let first = (increment, part);
        let second = (increment, count - part);
        if part != count - part && !used.contains(&first) && !used.contains(&second) {
            return Some(vec![first, second]);
        }
    }
    None
}

type SpanCache = BTreeMap<(i64, i64, i64), Vec<(Vec<Stage>, f64)>>;

fn try_calendar(
    starts: &[i64],
    months: &[i64],
    factor: i64,
    rng: &mut PythonRandom,
    noise: f64,
    cache: &mut SpanCache,
) -> Option<Vec<Stage>> {
    let mut used = BTreeSet::new();
    let mut rows = Vec::new();
    let mut current: Option<Stage> = None;
    let mut slack = 0;

    for k in 0..starts.len() - 1 {
        let mut candidates = Vec::new();
        let max_early = if k + 2 < starts.len() {
            SLACK_MONTHS
        } else {
            0
        };
        for early in 0..=max_early {
            let key = (
                starts[k + 1] - starts[k],
                months[k + 1] - months[k] + slack - early,
                slack,
            );
            let options = cache
                .entry(key)
                .or_insert_with(|| span_options(key.0, key.1, key.2));
            for (runs, unevenness) in options.iter() {
                // random() is consumed even during the zero-noise first pass.
                let score = *unevenness
                    + (RUN_COST * runs.len() as i64) as f64
                    + (2 * early) as f64
                    + rng.random() * noise;
                candidates.push((score, early, runs.clone()));
            }
        }
        candidates.sort_by(|left, right| left.0.total_cmp(&right.0));

        let mut chosen = None;
        for (_, early, mut runs) in candidates {
            let mut closing = Vec::new();
            if let Some(open) = current {
                if open.0 == runs[0].0 {
                    runs[0].1 += open.1;
                } else {
                    closing.push(open);
                }
            }
            closing.extend_from_slice(&runs[..runs.len() - 1]);

            let mut taken = used.clone();
            let mut new = Vec::new();
            let mut valid = true;
            for run in closing {
                if let Some(split) = rows_for(run, &taken) {
                    taken.extend(split.iter().copied());
                    new.extend(split);
                } else {
                    valid = false;
                    break;
                }
            }
            let last = runs[runs.len() - 1];
            if valid && rows_for(last, &taken).is_some() {
                chosen = Some((taken, new, last, early));
                break;
            }
        }
        let (taken, new, last, early) = chosen?;
        used = taken;
        rows.extend(new);
        current = Some(last);
        slack = early;
    }

    let current = current?;
    let tail = (
        rounded_ratio(STANDARD_MONTHS * 100, factor),
        CALENDAR_TURNS - (starts[starts.len() - 1] - 1),
    );
    let closing = if current.0 == tail.0 {
        vec![(tail.0, current.1 + tail.1)]
    } else {
        vec![current, tail]
    };
    for run in closing {
        let split = rows_for(run, &used)?;
        used.extend(split.iter().copied());
        rows.extend(split);
    }
    Some(rows)
}

fn speed_stages_from(speed: &str, reign_months: &[i64], all_eras: &[Value]) -> Result<Vec<Stage>> {
    let factor = multiplier(speed)?;
    let mut starts = vec![1];
    starts.extend(engine_turns_from(all_eras, speed)?);
    let mut months = vec![0];
    months.extend_from_slice(reign_months);
    let mut rng = PythonRandom::seed_zero();
    let mut cache = SpanCache::new();

    for attempt in 0..TRIES {
        let noise = if attempt == 0 {
            0.0
        } else {
            1.0 + attempt as f64 / 20.0
        };
        if let Some(rows) = try_calendar(&starts, &months, factor, &mut rng, noise, &mut cache) {
            return Ok(rows);
        }
    }
    bail!("{speed}: no calendar avoids a repeated GameSpeed_Turns key")
}

fn calendar_from(data: &Value) -> Result<(i64, SpeedStages)> {
    let months = reign_months_from(data)?;
    let all_eras = eras_from(data)?;
    let mut result = BTreeMap::new();
    for speed in SPEEDS {
        let stages = if speed == "GAMESPEED_STANDARD" {
            STANDARD_STAGES.to_vec()
        } else {
            speed_stages_from(speed, &months, &all_eras)?
        };
        result.insert(speed.to_owned(), stages);
    }
    Ok((START_YEAR, result))
}

pub fn calendar(repo: &Repository) -> Result<(i64, BTreeMap<String, Vec<(i64, i64)>>)> {
    calendar_from(&load(repo)?)
}

pub fn turns_by_speed(repo: &Repository) -> Result<BTreeMap<String, Vec<i64>>> {
    let data = load(repo)?;
    let months = reign_months_from(&data)?;
    let (_, stages) = calendar_from(&data)?;
    Ok(SPEEDS
        .into_iter()
        .map(|speed| {
            (
                speed.to_owned(),
                months
                    .iter()
                    .map(|&month| turn_containing(month, &stages[speed]))
                    .collect(),
            )
        })
        .collect())
}

pub fn sql(value: Option<&str>) -> String {
    value.map(sql_quote).unwrap_or_else(|| "NULL".to_owned())
}

fn names(reign: &Value) -> Result<Vec<String>> {
    LANGS
        .iter()
        .map(|&(short, _)| Ok(string(reign, short)?.to_owned()))
        .collect()
}

fn build_from(data: &Value) -> Result<(String, String)> {
    let reigns = reign_list(data)?;
    let all_eras = eras_from(data)?;
    let engine: BTreeMap<_, _> = SPEEDS
        .iter()
        .map(|&speed| Ok((speed, engine_turns_from(&all_eras, speed)?)))
        .collect::<Result<_>>()?;

    let mut out = String::new();
    writeln!(out, "{GENERATED_SQL_HEADER}")?;
    out.push_str(
        "-- The 改元 after the start (天文) in date order, each with its engine era (Data/JAC_Sengoku_Eras.sql); the\n\
         -- ledger judges when that era starts. Trailing comment: that turn at the online / quick / standard / epic /\n\
         -- marathon speeds.\n\
         INSERT INTO JAC_SengokuReigns (ReignType, Year, Month, Name, Announcement, Notification, ForcedAge, EraType) VALUES\n",
    );
    for (index, reign) in reigns.iter().enumerate() {
        let id = string(reign, "id")?;
        let key = format!("LOC_JAC_REIGN_{id}");
        let forced_age = match reign.get("forced_age") {
            None | Some(Value::Null) => None,
            Some(value) => Some(
                value
                    .as_str()
                    .ok_or_else(|| anyhow!("expected forced_age string for {id}"))?,
            ),
        };
        let values = [
            sql_quote(&format!("REIGN_{id}")),
            integer(reign, "year")?.to_string(),
            integer(reign, "month")?.to_string(),
            sql_quote(&format!("{key}_NAME")),
            sql_quote(&format!("{key}_ANNOUNCEMENT")),
            sql_quote(&format!("{key}_NOTIFICATION")),
            sql(forced_age),
            sql_quote(string(&all_eras[index + 1], "EraType")?),
        ]
        .join(", ");
        let at = SPEEDS
            .iter()
            .map(|speed| engine[speed][index].to_string())
            .collect::<Vec<_>>()
            .join(" / ");
        let punctuation = if index + 1 < reigns.len() { ',' } else { ';' };
        writeln!(
            out,
            "  ({values}){punctuation} -- {} {at}",
            string(reign, "ja")?
        )?;
    }

    let start = start_reign(data)?;
    let mut text: IndexMap<String, Vec<String>> = IndexMap::new();
    text.insert(
        format!("LOC_JAC_REIGN_{}_NAME", string(start, "id")?),
        names(start)?,
    );
    let mut previous = start;
    for reign in reigns {
        let key = format!("LOC_JAC_REIGN_{}", string(reign, "id")?);
        text.insert(format!("{key}_NAME"), names(reign)?);
        let year = integer(reign, "year")?;
        let mut announcements = Vec::new();
        let mut notifications = Vec::new();
        for (short, lang) in LANGS {
            let p = string(previous, short)?;
            let n = string(reign, short)?;
            let (announcement, notification) = match lang {
                "ja_JP" => (
                    format!("改元[NEWLINE]{p}から{n}へ（{year}年）"),
                    format!("改元：{n}の世"),
                ),
                "en_US" => (
                    format!("New era name:[NEWLINE]from {p} to {n} ({year})"),
                    format!("New era name: {n} Era"),
                ),
                "ru_RU" => (
                    format!("Смена девиза правления:[NEWLINE]с {p} на {n} ({year})"),
                    format!("Смена девиза: эпоха {n}"),
                ),
                _ => unreachable!("LANGS contains only the three supported languages"),
            };
            announcements.push(announcement);
            notifications.push(notification);
        }
        text.insert(format!("{key}_ANNOUNCEMENT"), announcements);
        text.insert(format!("{key}_NOTIFICATION"), notifications);
        previous = reign;
    }
    for reign in std::iter::once(start).chain(reigns.iter()) {
        let by_lang = LANGS
            .iter()
            .map(|&(short, lang)| {
                let n = string(reign, short)?;
                Ok(match lang {
                    "ja_JP" => format!("{n}の世"),
                    "en_US" => format!("{n} Era"),
                    "ru_RU" => format!("Эпоха {n}"),
                    _ => unreachable!("LANGS contains only the three supported languages"),
                })
            })
            .collect::<Result<Vec<_>>>()?;
        text.insert(
            format!("LOC_JAC_ERA_{}_NAME", string(reign, "id")?),
            by_lang,
        );
    }

    let mut xml = String::from("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
    writeln!(xml, "{GENERATED_XML_HEADER}")?;
    xml.push_str("<GameData>\n  <LocalizedText>\n");
    for (key, by_lang) in text {
        for (index, (_, lang)) in LANGS.iter().enumerate() {
            writeln!(
                xml,
                "    <Row Tag=\"{key}\" Language=\"{lang}\"><Text>{}</Text></Row>",
                xml_escape(&by_lang[index])
            )?;
        }
    }
    xml.push_str("  </LocalizedText>\n</GameData>\n");
    Ok((out, xml))
}

pub fn build(repo: &Repository) -> Result<(String, String)> {
    build_from(&load(repo)?)
}

fn build_eras_from(data: &Value) -> Result<String> {
    let all_eras = eras_from(data)?;
    let official_count = OFFICIAL_ERAS.len().min(all_eras.len());
    let (official, added) = all_eras.split_at(official_count);
    let source = sql_quote(OFFICIAL_ERAS[OFFICIAL_ERAS.len() - 1]);
    let mut out = String::new();
    writeln!(out, "{GENERATED_SQL_HEADER}")?;
    out.push_str(
        "-- 元号 = 時代 (owner decision T, SSOT 3.2, documents/poc/era-equals-reign.md): one engine era per reign. The\n\
         -- 9 official eras keep their IDs and take the first 9 reigns' names; the other reigns are new eras after them.\n\
         -- Each era lasts its reign's standard turns (Eras_XP1 minimum = maximum; the engine scales other speeds by\n\
         -- GameSpeeds.CostMultiplier) and 遅代 never ends (NULL/NULL like the official ERA_FUTURE,\n\
         -- DLC/Expansion2/Data/Expansion1_Eras.xml:12; both columns may be NULL, Expansion2_Schema.sql:293-299).\n\
         -- A countdown of 1 (official 10, DLC/Expansion2/Data/Expansion2_GlobalParameters.xml:204) announces the\n\
         -- change only on the turn before it.\n\
         INSERT OR REPLACE INTO GlobalParameters (Name, Value) VALUES ('NEXT_ERA_TURN_COUNTDOWN', '1');\n\
         \n\
         -- Official eras renamed (Base/Assets/Gameplay/Data/Eras.xml:16-23, DLC/Expansion2/Data/Expansion2_Eras.xml:7);\n\
         -- the description is the name too.\n",
    );
    for era in official {
        let name = sql_quote(&format!("LOC_JAC_ERA_{}_NAME", string(era, "id")?));
        writeln!(
            out,
            "UPDATE Eras SET Name={name}, Description={name} WHERE EraType={};",
            sql_quote(string(era, "EraType")?)
        )?;
    }
    const COLUMNS: &str =
        "WarmongerPoints, GreatPersonBaseCost, EraTechBackgroundTexture, EraCivicBackgroundTexture, WarmongerLevelDescription, EmbarkedUnitStrength, EraTechBackgroundTextureOffsetX, EraCivicBackgroundTextureOffsetX, TechTreeLayoutMethod";
    out.push_str(
        "\n\
         -- New eras. The other Eras columns and the per-era rows of Eras_XP1 (LiberatedEnvoys) and Eras_XP2 copy\n\
         -- ERA_FUTURE, the last official era (DLC/Expansion2/Data/Expansion2_Eras.xml:7,73,\n\
         -- DLC/Expansion2/Data/Expansion1_Eras.xml:12). No other per-era table needs a row for an era that is not a\n\
         -- start era (documents/poc/era-equals-reign.md).\n\
         INSERT INTO Types (Type, Kind) VALUES\n",
    );
    let type_rows = added
        .iter()
        .map(|era| {
            Ok(format!(
                "  ({}, 'KIND_ERA')",
                sql_quote(string(era, "EraType")?)
            ))
        })
        .collect::<Result<Vec<_>>>()?;
    out.push_str(&type_rows.join(",\n"));
    out.push_str(";\n");
    for era in added {
        let era_type = sql_quote(string(era, "EraType")?);
        let name = sql_quote(&format!("LOC_JAC_ERA_{}_NAME", string(era, "id")?));
        let chronology = integer(era, "ChronologyIndex")?;
        writeln!(
            out,
            "INSERT INTO Eras (EraType, Name, Description, ChronologyIndex, {COLUMNS}) SELECT {era_type}, {name}, {name}, {chronology}, {COLUMNS} FROM Eras WHERE EraType={source};"
        )?;
        writeln!(
            out,
            "INSERT INTO Eras_XP1 (EraType, LiberatedEnvoys) SELECT {era_type}, LiberatedEnvoys FROM Eras_XP1 WHERE EraType={source};"
        )?;
        writeln!(
            out,
            "INSERT INTO Eras_XP2 (EraType, GrievanceDecayRate, TensionDecayRate, TradeRouteMinimumEndTurnChange, EraScoreThresholdShift) SELECT {era_type}, GrievanceDecayRate, TensionDecayRate, TradeRouteMinimumEndTurnChange, EraScoreThresholdShift FROM Eras_XP2 WHERE EraType={source};"
        )?;
    }
    out.push_str(
        "\n\
         -- Era lengths: the standard turns from the reign's 改元 to the next (the calendar turn containing each month).\n\
         -- Official 40/60 (DLC/Expansion2/Data/Expansion1_Eras.xml:3-12).\n",
    );
    for era in &all_eras {
        let length = match era.get("length") {
            Some(Value::Null) => "NULL".to_owned(),
            Some(value) => value
                .as_i64()
                .context("expected integer era length")?
                .to_string(),
            None => bail!("missing era length"),
        };
        writeln!(
            out,
            "UPDATE Eras_XP1 SET GameEraMinimumTurns={length}, GameEraMaximumTurns={length} WHERE EraType={}; -- {}",
            sql_quote(string(era, "EraType")?),
            string(era, "id")?
        )?;
    }
    let late = LATE_OFFICIAL_ERA_YEARS
        .iter()
        .map(|&(era, _)| sql_quote(era))
        .collect::<Vec<_>>()
        .join(", ");
    out.push_str(
        "\n\
         -- Owner decision U-3b: the official great people of the Industrial to Future eras do not appear in the\n\
         -- Sengoku pack (they would arrive with 天正 to 寛永). Deleting their Types rows cascades to\n\
         -- GreatPersonIndividuals (01_GameplaySchema.sql:1519,1566) and on to their great works, action and birth\n\
         -- modifiers and the journalism visibility source (ON DELETE CASCADE, :1012,1573,1579,1598).\n",
    );
    writeln!(
        out,
        "DELETE FROM Types WHERE Type IN (SELECT GreatPersonIndividualType FROM GreatPersonIndividuals WHERE EraType IN ({late}));"
    )?;
    out.push_str(
        "-- The great works of those eras with no great person (the industrial artifacts GREATWORK_ARTIFACT_21-25,\n\
         -- Base/Assets/Gameplay/Data/GreatWorks.xml) go to the reign of the official era's start year\n\
         -- (LATE_OFFICIAL_ERA_YEARS in the generator).\n",
    );
    for (era_type, year) in LATE_OFFICIAL_ERA_YEARS {
        writeln!(
            out,
            "UPDATE GreatWorks SET EraType={} WHERE EraType={}; -- {year}",
            sql_quote(&era_of_date_from(data, &all_eras, year, 1)?),
            sql_quote(era_type)
        )?;
    }
    Ok(out)
}

