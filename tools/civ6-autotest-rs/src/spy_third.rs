//! The opt-in third generation connection is authored and generated in Rust.
//! It reuses Boundary's native BUILD, AddProgress, travel and mission routes.
//! UI-only history/roster/queue values cross as immutable scalar observations;
//! Gameplay independently checks units, civic ownership and title accounting.
//! Installed evidence: Base/Assets/UI/Panels/ProductionPanel.lua:293-301 and
//! Debug/City.ltp:200-204. A third operative remains unproven on a real game.
use std::path::Path;

pub const OUTPUT: &str = "poc/JAC_Test_PersonaBoundary/Shared/JAC_PersonaThirdSpy.lua";
pub const GENERATION: u8 = 3;
pub const OLD_IDS: [u32; 2] = [655368, 851976];
pub const OLD_EVENTS: [(u32, u32); 2] = [(0, 23), (1, 45)];

pub fn connection() -> String {
    format!(
        "-- Generated by spy-third-generate; edit tools/civ6-autotest-rs/src/spy_third.rs.\n\
         -- Test-only native connection; no unit/capacity setters or inferred captive identities.\n\
         local R=JAC_PersonaBoundaryRules; local T={{generation={GENERATION},oldIDs={{{},{}}},oldEvents={{{{{},{}}},{{{},{}}}}}}}; R.Third=T;\n{}",
        OLD_IDS[0], OLD_IDS[1], OLD_EVENTS[0].0, OLD_EVENTS[0].1, OLD_EVENTS[1].0, OLD_EVENTS[1].1, LUA
    )
}

pub fn write_connection(root: &Path, check: bool) -> std::io::Result<()> {
    let path = root.join(OUTPUT);
    let expected = connection();
    if check {
        if std::fs::read_to_string(&path)?.replace("\r\n", "\n") != expected {
            return Err(std::io::Error::other(
                "third spy connection differs from its Rust generator",
            ));
        }
    } else {
        let current = std::fs::read_to_string(&path).ok();
        if current.as_deref().map(|v| v.replace("\r\n", "\n")) != Some(expected.clone()) {
            std::fs::write(path, expected)?;
        }
    }
    Ok(())
}

