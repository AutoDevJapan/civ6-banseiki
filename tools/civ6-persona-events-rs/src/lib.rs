pub fn embed(source: &str) -> Result<String, String> {
    fn section(
        source: &str,
        begin: &str,
        end_marker: &str,
        adapter: &str,
        anchor: &str,
    ) -> Result<String, String> {
        let block = format!("{begin}\n{adapter}{end_marker}\n");
        if let Some(start) = source.find(begin) {
            let end = source[start..]
                .find(end_marker)
                .ok_or("events block end missing")?
                + start
                + end_marker.len();
            return Ok(format!(
                "{}{}{}",
                &source[..start],
                block.trim_end(),
                &source[end..]
            ));
        }
        let at = source
            .find(anchor)
            .ok_or("Gameplay lexical anchor missing")?;
        Ok(format!("{}{}\n{}", &source[..at], block, &source[at..]))
    }
    let source = section(
        source,
        BEGIN,
        END,
        adapter(),
        "local function NativeGovernor(owner, row)",
    )?;
    let source = section(
        &source,
        REPUBLISH_BEGIN,
        REPUBLISH_END,
        republish_adapter(),
        "-- BEGIN RUST GENERATED PAID ASSIGNMENT GLUE",
    )?;
    let source = route(
        &source,
        "local function NativeGovernor(owner, row)",
        "-- Private cost-one",
        normal::NATIVE,
    )?;
    let source = route(
        &source,
        "local function CorePaymentRead(owner, row, cost)",
        "local function ReservedOutstandingCost",
        normal::PAYMENT,
    )?;
    // Keep the shared UI reader unchanged; only Gameplay reservation callers
    // use the synchronized sets. The private diagnostic retains its old route.
    let source = source.replace(
        "Rules.ReservedAppointments(owner)",
        "PersonaEvents.Reserved(owner, Rules.ReservedAppointments)",
    );
    // Export a detached read-only snapshot through the existing Gameplay table.
    let source = source.replace(
        "    EventsGameplayStatus = PersonaEvents.NormalStatus,\n",
        "",
    );
    Ok(source.replace("    EventsProbeStatus = PersonaEvents.Status,",
        "    EventsProbeStatus = PersonaEvents.Status,\n    EventsGameplayStatus = PersonaEvents.NormalStatus,"))
}

fn route(source: &str, start: &str, next: &str, generated: &str) -> Result<String, String> {
    let at = source.find(start).ok_or("normal route start missing")?;
    let end = source[at..].find(next).ok_or("normal route end missing")? + at;
    Ok(format!(
        "{}{}\n{}",
        &source[..at],
        generated,
        &source[end..]
    ))
}
