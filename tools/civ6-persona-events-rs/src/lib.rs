//! Opt-in synchronous Gameplay receipts. No UI reader, payment sender or native patch.
pub mod scenario;

pub const BEGIN: &str = "-- BEGIN RUST PERSONA EVENTS PROBE";
pub const END: &str = "-- END RUST PERSONA EVENTS PROBE";
pub const GAMEPLAY: &str = "poc/JAC_PoC_LeaderPersona/Scripts/JAC_LeaderPersona_Gameplay.lua";

/// Emitted inside the Gameplay lexical scope, after Get/Definition/Player.
pub fn adapter() -> &'static str {
    r#"-- Generated by civ6-persona-events-rs; edit its Rust source.
local PersonaEvents = {}
do
local E = PersonaEvents
local FLAG = 'JAC_TEST324_EVENTS_PROBE'
local STORE = 'JAC_PERSONA_EVENTS_PROBE_V1'
local SOURCE = 'civ6-persona-events-rs/v1/Gameplay'
local registrations = {}
local function integer(v) return type(v)=='number' and v>=0 and v<9007199254740991 and v%1==0 end
local function copy(v)
    if type(v)~='table' then return v end
    local t={}; for k,x in pairs(v) do t[k]=copy(x) end; return t
end
local function spent(owner)
    local p=Player(owner,true); local g=p and p:GetGovernors()
    if not g or type(g.GetGovernorPointsSpent)~='function' then return nil end
    local ok,n=pcall(g.GetGovernorPointsSpent,g)
    return ok and integer(n) and n or nil
end
local function signature(row)
    if not row or type(row.LeaderType)~='string' or row.EvolutionCost~=2 or
       row.GovernorType~='GOVERNOR_JAC_PERSONA_'..string.sub(row.LeaderType,12) then return nil end
    local gov=GameInfo.Governors[row.GovernorType]
    local base=GameInfo.GovernorPromotions[row.BasePromotionType]
    local title=GameInfo.GovernorPromotions[row.BasePromotionType..'_TITLE_1']
    if not gov or not base or not title or not integer(gov.Index) or not integer(base.Index) or
       not integer(title.Index) or base.Index==title.Index or gov.GovernorType~=row.GovernorType or
       base.GovernorPromotionType~=row.BasePromotionType or title.GovernorPromotionType~=row.BasePromotionType..'_TITLE_1' then return nil end
    -- Ambiguous indices/types anywhere in the live catalog cannot prove identity.
    local leaders,governors,count={},{},0
    for person in GameInfo.JAC_LeaderPersonas() do
        local d=GameInfo.Governors[person.GovernorType]
        if not d or not integer(d.Index) or governors[d.Index] or leaders[person.LeaderType] then return nil end
        governors[d.Index]=true; leaders[person.LeaderType]=true; count=count+1
    end
    if count~=22 then return nil end
    local indices,types={},{}
    for promotion in GameInfo.GovernorPromotions() do
        if not integer(promotion.Index) or type(promotion.GovernorPromotionType)~='string' or indices[promotion.Index] or types[promotion.GovernorPromotionType] then return nil end
        indices[promotion.Index]=true; types[promotion.GovernorPromotionType]=true
    end
    if not indices[base.Index] or not indices[title.Index] then return nil end
    return {leader=row.LeaderType, governorType=gov.GovernorType, governor=gov.Index,
        baseType=base.GovernorPromotionType, base=base.Index,
        titleType=title.GovernorPromotionType, title=title.Index, cost=row.EvolutionCost}
end
local function same(a,b)
    if type(a)~='table' or type(b)~='table' then return false end
    for _,k in ipairs({'leader','governorType','governor','baseType','base','titleType','title','cost'}) do
        if a[k]~=b[k] then return false end
    end
    return true
end
local function validProof(p,s,kind)
    if p==nil then return true end
    local isApp=kind=='appointed'
    local promo=kind=='title' and s.definition.title or s.definition.base
    if type(p)~='table' or type(p.raw)~='table' then return false end
    for i,want in ipairs({s.owner,s.definition.governor}) do
        if type(p.raw[i])~='table' or p.raw[i].type~='number' or p.raw[i].value~=want then return false end
    end
    if not isApp and (type(p.raw[3])~='table' or p.raw[3].type~='number' or p.raw[3].value~=promo) then return false end
    return p.accepted==true and p.reason=='acquired' and p.source==SOURCE and p.context=='Gameplay' and
        p.resolvedLeader==s.leader and p.resolvedGovernor==s.definition.governor and
        p.resolvedGovernorType==s.definition.governorType and
        (isApp or (p.resolvedPromotion==promo and p.resolvedPromotionType==(kind=='title' and s.definition.titleType or s.definition.baseType))) and
        p.owner==s.owner and p.leader==s.leader and
        p.governor==s.definition.governor and p.promotion==(isApp and -1 or promo) and
        p.name==(isApp and 'GovernorAppointed' or 'GovernorPromoted') and
        p.arity==(isApp and 2 or 3) and integer(p.sequence) and p.sequence>0 and p.sequence<=s.sequence and
        integer(p.turn) and p.turn<=Game.GetCurrentGameTurn() and integer(p.spent) and p.spent>=s.baseline+(kind=='title' and 2 or 1)
end
local function state()
    if Game:GetProperty(FLAG)~=1 then return nil,'disabled' end
    local s=Game:GetProperty(STORE)
    if type(s)~='table' or s.version~=1 or s.source~=SOURCE or not integer(s.owner) or
       type(s.leader)~='string' or not integer(s.sourcePlayer) or s.baseline~=0 or
       not integer(s.sequence) or type(s.acquired)~='table' or type(s.receipts)~='table' or #s.receipts>64 then return nil,'foreign-schema' end
    local row=Definition(s.leader)
    if not same(s.definition,signature(row)) then return nil,'definition-changed' end
    local sequences={}
    for k in pairs(s.acquired) do
        if k~='appointed' and k~='base' and k~='title' then return nil,'invalid-proof' end
    end
    for _,k in ipairs({'appointed','base','title'}) do
        if not validProof(s.acquired[k],s,k) then return nil,'invalid-proof' end
        local p=s.acquired[k]
        if p then
            if sequences[p.sequence] then return nil,'mixed-proof-sequence' end
            sequences[p.sequence]=true
        end
    end
    local cfg=PlayerConfigurations[s.sourcePlayer]
    if not cfg or cfg:GetLeaderTypeName()~=s.leader then return nil,'source-changed' end
    return s
end
function E.Enabled() return Game:GetProperty(FLAG)==1 end
function E.Scope(owner,row)
    local s=state(); return s and s.owner==owner and row and s.leader==row.LeaderType and s or nil
end
local function joined(s)
    local phase=Get(s.leader,'STATE')
    return Get(s.leader,'OWNER')==s.owner and Get(s.leader,'SOURCE')==s.sourcePlayer and
        Get(s.leader,'EVOLUTION_COST')==2 and (phase=='EVOLVING' or phase=='GOVERNOR')
end
function E.Paid(owner,row,cost)
    local s=E.Scope(owner,row)
    if not s or cost~=2 or not joined(s) or not s.acquired.appointed or not s.acquired.base then return nil,false end
    local paid=s.acquired.title and 2 or 1
    local n=spent(owner); if not n or n<s.baseline+paid then return nil,true end
    return paid,true
end
function E.Native(owner,row)
    local paid=E.Paid(owner,row,2)
    if paid then return {appointed=true,base=true,surchargePaid=paid-1,source=SOURCE} end
    -- Zero official spending in the strictly fresh probe is absence evidence,
    -- never positive per-person attribution. No old partial save can enter it.
    local s=E.Scope(owner,row)
    if s and spent(owner)==0 and not next(s.acquired) and
       (Get(s.leader,'OWNER')==nil or Get(s.leader,'OWNER')==owner) then
        return {appointed=false,base=false,surchargePaid=0,source=SOURCE}
    end
    return nil
end
function E.Start(owner,source)
    if Game:GetProperty(FLAG)~=nil or Game:GetProperty(STORE)~=nil then return false,'already-started' end
    if not integer(owner) or not integer(source) or owner==source or not Player(owner,true) or not Player(source,false) then return false,'invalid-owner' end
    local cfg=PlayerConfigurations[source]; local leader=cfg and cfg:GetLeaderTypeName()
    local row=Definition(leader); local def=signature(row)
    if not def or cfg:GetCivilizationTypeName()~=row.CivilizationType then return false,'invalid-definition' end
    local ids=PlayerManager.GetAliveMajorIDs(); local seen,count={},0
    if type(ids)~='table' then return false,'invalid-players' end
    for _,id in pairs(ids) do
        if not integer(id) or seen[id] or spent(id)~=0 then return false,'not-fresh' end
        seen[id]=true; count=count+1
    end
    if count~=22 or not seen[owner] or not seen[source] then return false,'invalid-players' end
    for person in GameInfo.JAC_LeaderPersonas() do
        if Get(person.LeaderType,'OWNER')~=nil then return false,'not-fresh' end
    end
    for _,name in ipairs({'GovernorAppointed','GovernorPromoted'}) do
        if not registrations[name] or not registrations[name].callOK then return false,'subscription-unavailable' end
    end
    if Game:GetProperty('JAC_TEST853_ADMISSION_ACTIVE')~=nil or Game:GetProperty('JAC_TEST853_ADMISSION_MANUAL_APPOINT')~=nil then return false,'other-probe' end
    Game:SetProperty(STORE,{version=1,source=SOURCE,owner=owner,sourcePlayer=source,leader=leader,
        definition=def,baseline=0,sequence=0,acquired={},receipts={}})
    Game:SetProperty('JAC_TEST853_ADMISSION_ACTIVE',1)
    Game:SetProperty('JAC_TEST853_ADMISSION_MANUAL_APPOINT',1)
    Game:SetProperty(FLAG,1)
    return true,'ready'
end
local function receive(name,...)
    local s=state(); if not s then return end
    if s.sequence>=9007199254740990 then return end
    local arity=select('#',...); local args={...}; local raw={}
    for i=1,math.min(arity,8) do
        local v=args[i]; local t=type(v)
        local value=v
        if t~='number' and t~='boolean' then value=string.sub(tostring(v),1,128) end
        if t=='number' and (v~=v or v==math.huge or v==-math.huge) then value=tostring(v) end
        raw[i]={type=t,value=value}
    end
    s.sequence=s.sequence+1
    local r={source=SOURCE,context='Gameplay',name=name,arity=arity,raw=raw,
        sequence=s.sequence,turn=Game.GetCurrentGameTurn(),accepted=false,reason='arguments',
        spent=integer(args[1]) and spent(args[1]) or nil}
    local app=name=='GovernorAppointed'
    if arity==(app and 2 or 3) and integer(args[1]) and integer(args[2]) and (app or integer(args[3])) then
        r.owner=args[1]; r.governor=args[2]; r.promotion=app and -1 or args[3]
        local d=GameInfo.Governors[args[2]]
        local p=not app and GameInfo.GovernorPromotions[args[3]] or nil
        r.resolvedGovernor=d and d.Index; r.resolvedGovernorType=d and d.GovernorType
        r.resolvedPromotion=p and p.Index; r.resolvedPromotionType=p and p.GovernorPromotionType
        for row in GameInfo.JAC_LeaderPersonas() do
            if d and row.GovernorType==d.GovernorType then r.resolvedLeader=row.LeaderType end
        end
        r.leader=s.leader
        local key=app and 'appointed' or (args[3]==s.definition.base and 'base' or (args[3]==s.definition.title and 'title' or nil))
        r.reason='wrong-person-or-owner'
        if args[1]==s.owner and args[2]==s.definition.governor and d and d.Index==args[2] and
           d.GovernorType==s.definition.governorType and key and
           (app or (p and p.Index==args[3] and p.GovernorPromotionType==(key=='base' and s.definition.baseType or s.definition.titleType))) then
            r.reason='not-joined'
            if joined(s) then
                r.reason='official-spent'
                if integer(r.spent) and r.spent>=s.baseline+(key=='title' and 2 or 1) then
                    r.accepted=true; r.reason=s.acquired[key] and 'duplicate' or 'acquired'
                    if not s.acquired[key] then s.acquired[key]=copy(r) end
                elseif s.acquired[key] then
                    -- A late BASE/Appointed duplicate may arrive after TITLE.
                    r.accepted=true; r.reason='duplicate'
                end
            end
        end
    end
    s.receipts[#s.receipts+1]=r
    if #s.receipts>64 then table.remove(s.receipts,1) end
    Game:SetProperty(STORE,s)
    print('JAC_PERSONA_EVENTS324 '..name..' seq='..r.sequence..' arity='..arity..' result='..r.reason..' spent='..tostring(r.spent))
end
-- Events uses __index in Civ6. Read event, Add, and call separately; pairs is
-- deliberately never an availability test. Call Add as the official scripts do.
for _,name in ipairs({'GovernorAppointed','GovernorPromoted'}) do
    local reg={}; registrations[name]=reg
    local ok,event=pcall(function() return Events[name] end); reg.indexOK=ok; reg.eventPresent=ok and event~=nil
    if reg.eventPresent then
        local addOK,add=pcall(function() return event.Add end); reg.addOK=addOK; reg.addFunction=addOK and type(add)=='function'
        if reg.addFunction then
            reg.callOK=pcall(add,function(...) receive(name,...) end)
        end
    end
end
function E.Status(owner,leader)
    local s,reason=state(); local row=Definition(leader)
    local result={source=SOURCE,context='Gameplay',active=E.Enabled(),reason=reason,
        registrations=copy(registrations),owner=owner,leader=leader,spent=spent(owner)}
    if s and row and s.owner==owner and s.leader==leader then
        result.definition=copy(s.definition); result.sequence=s.sequence
        result.acquired=copy(s.acquired); result.receipts=copy(s.receipts)
        result.paid,result.readable=E.Paid(owner,row,row.EvolutionCost)
        result.native=E.Native(owner,row)
    end
    return result
end
GameEvents.JAC_LeaderPersonaEventsProbe.Add(function(owner,params)
    local ok,reason=E.Start(owner,type(params)=='table' and params.Source or nil)
    Finish(owner,ok and 'EVENT_PROBE_READY' or ('EVENT_PROBE_'..reason))
end)
end
"#
}

pub fn embed(source: &str) -> Result<String, String> {
    let block = format!("{BEGIN}\n{}{END}\n", adapter());
    if let Some(start) = source.find(BEGIN) {
        let end = source[start..]
            .find(END)
            .ok_or("events block end missing")?
            + start
            + END.len();
        return Ok(format!(
            "{}{}{}",
            &source[..start],
            block.trim_end(),
            &source[end..]
        ));
    }
    let anchor = "local function NativeGovernor(owner, row)";
    let at = source
        .find(anchor)
        .ok_or("Gameplay lexical anchor missing")?;
    Ok(format!("{}{}\n{}", &source[..at], block, &source[at..]))
}
