//! Source-derived official StagingRoom cap adjustment. No native/game writes.
//! The generated stock file is local output, never copied into the repository.
use serde_json::json;
use sha2::{Digest, Sha256};
use std::path::Path;

pub const STOCK_SHA: &str = "e05b89a60e9d79cf2161e196cd0e0ce8e3a236443070359dc1cf9393c563133e";
pub const MOD_ID: &str = "28d32422-76af-475d-93a7-8d840dcde726";
pub const MOD_FOLDER: &str = "JAC_Test_Staging22";
pub const MAPS: [&str; 4] = [
    "{403be889-1455-4de7-967b-ad54c0ff3431}Maps/JAC_Japan_15km.Civ6Map",
    "{403be889-1455-4de7-967b-ad54c0ff3431}Maps/JAC_Japan_20km.Civ6Map",
    "{403be889-1455-4de7-967b-ad54c0ff3431}Maps/JAC_Japan_15km_Settlers.Civ6Map",
    "{403be889-1455-4de7-967b-ad54c0ff3431}Maps/JAC_Japan_20km_Settlers.Civ6Map",
];
pub fn sha(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}
pub fn policy() -> String {
    let maps = MAPS
        .iter()
        .map(|m| format!("['{m}']=true"))
        .collect::<Vec<_>>()
        .join(",\n");
    format!(
        r#"-- Generated by civ6-persona-events-rs: scoped staging22/v1.
local JAC_StagingMaps={{{maps}}}
local function JAC_StagingCap()
 if GameConfiguration.IsHotseat()==true and GameConfiguration.GetRuleSet()=='RULESET_JAC_BANSEIKI'
  and JAC_StagingMaps[MapConfiguration.GetValue('MAP_SCRIPT')]==true then return 22 end
 return 12
end
"#
    )
}
const SETTER: &str = "g_currentMaxPlayers = math.min(newMaxPlayers, MAX_EVER_PLAYERS);";
const SCOPED_SETTER: &str = "g_currentMaxPlayers = math.min(newMaxPlayers, JAC_StagingCap());";
const CHANGE: &str = "if(g_currentMaxPlayers ~= newMaxPlayers) then";
const SCOPED_CHANGE: &str =
    "if(g_currentMaxPlayers ~= newMaxPlayers or g_currentMaxPlayers ~= math.min(newMaxPlayers, JAC_StagingCap())) then";
const SHOW: &str = "g_currentMaxPlayers = math.min(MapConfiguration.GetMaxMajorPlayers(), 12);";
const SCOPED_SHOW: &str = "SetCurrentMaxPlayers(MapConfiguration.GetMaxMajorPlayers());";
