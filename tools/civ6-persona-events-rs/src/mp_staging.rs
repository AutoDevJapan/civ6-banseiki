fn once(s: &str, old: &str, new: &str) -> Result<String, String> {
    if s.matches(old).count() != 1 {
        return Err(format!("official source anchor must occur once: {old}"));
    }
    Ok(s.replacen(old, new, 1))
}
fn transform_text(source: &str) -> Result<String, String> {
    let s = once(
        source,
        "function SetCurrentMaxPlayers(",
        &format!("{}\nfunction SetCurrentMaxPlayers(", policy()),
    )?;
    let s = once(&s, SETTER, SCOPED_SETTER)?;
    let s = once(&s, CHANGE, SCOPED_CHANGE)?;
    let s = once(&s, SHOW, SCOPED_SHOW)?;
    once(&s, "\nInitialize();", &format!("{STATUS}\nInitialize();"))
}
pub fn transform(stock: &[u8]) -> Result<String, String> {
    if sha(stock) != STOCK_SHA {
        return Err(
            "installed StagingRoom differs from reviewed stock SHA; no output produced".into(),
        );
    }
    transform_text(
        &String::from_utf8(stock.to_vec())
            .map_err(|e| e.to_string())?
            .replace("\r\n", "\n"),
    )
}
pub fn manifest() -> String {
    format!(
        r#"<?xml version="1.0" encoding="utf-8"?>
<Mod id="{MOD_ID}" version="1">
 <Properties><Name>JAC staging22 boundary</Name><Description>Scoped official hotseat staging cap; native22 remains unverified.</Description><Authors>civ6-banseiki</Authors><CompatibleVersions>2.0</CompatibleVersions></Properties>
 <FrontEndActions><ImportFiles id="JAC_Staging22"><Properties><LoadOrder>450</LoadOrder></Properties><File>UI/StagingRoom.lua</File></ImportFiles></FrontEndActions>
 <Files><File>UI/StagingRoom.lua</File></Files>
</Mod>
"#
    )
}
pub fn prepare(stock: &[u8], out: &Path) -> Result<(), String> {
    let patched = transform(stock)?;
    let manifest = manifest();
    if out.exists() {
        return Err("output must not exist; preserve prior candidate".into());
    }
    std::fs::create_dir_all(out.join(MOD_FOLDER).join("UI")).map_err(|e| e.to_string())?;
    std::fs::write(out.join(MOD_FOLDER).join("UI/StagingRoom.lua"), &patched)
        .map_err(|e| e.to_string())?;
    std::fs::write(
        out.join(MOD_FOLDER).join(format!("{MOD_FOLDER}.modinfo")),
        &manifest,
    )
    .map_err(|e| e.to_string())?;
    let proof = json!({"stock_sha256":STOCK_SHA,"generated_sha256":sha(patched.as_bytes()),"manifest_sha256":sha(manifest.as_bytes()),"mod_id":MOD_ID,"deployment":"parent only under own game/lock; no installedstock/native overwrite; exclude competing StagingRoom overrides","native_capacity":"not_proven","source":"civ6-persona-events-rs/mp_staging"});
    std::fs::write(
        out.join("bundle.json"),
        serde_json::to_vec_pretty(&proof).unwrap(),
    )
    .map_err(|e| e.to_string())
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn exact_anchor_rejects_missing_and_duplicate_and_hash_rejects_other_stock() {
        assert!(once("x x", "x", "z").is_err());
        assert!(once("z", "x", "y").is_err());
        assert!(transform(b"unreviewed stock").is_err());
    }
    #[test]
    fn transformation_has_only_reviewed_replacements() {
        let original=format!("function SetCurrentMaxPlayers(newMaxPlayers)\n{SETTER}\nend\nfunction Changed(newMaxPlayers)\n{CHANGE}\nend\nend\nfunction OnShow()\n{SHOW}\nend\nInitialize();\n");
        let changed = transform_text(&original).unwrap();
        let restored = changed
            .replace(&format!("{}\n", policy()), "")
            .replace(STATUS, "")
            .replace(SCOPED_SETTER, SETTER)
            .replace(SCOPED_CHANGE, CHANGE)
            .replace(SCOPED_SHOW, SHOW);
        assert_eq!(restored, original);
    }
}
