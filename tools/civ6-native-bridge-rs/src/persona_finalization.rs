//! Generate Gameplay's receipt validator, payment completion and the minimal
//! reconciliation guard. Native readers and existing reconciliation stay intact.

const BEGIN: &str = "-- BEGIN RUST GENERATED PERSONA FINALIZATION";
const END: &str = "-- END RUST GENERATED PERSONA FINALIZATION";
const FUNCTION: &str = "local function CompleteEvolution(owner, leader)";
const NEXT: &str = "local function Reconcile(onlyOwner)";
const AFTER_RECONCILE: &str = "local function Parameter(name)";
const READ: &str = "            local native = NativeGovernor(owner, row);";
const TAIL: &str = "        end\n    end\n    SyncProductionAdmission(false, onlyOwner);\nend\n\n";

pub fn reconcile_open_source() -> &'static str {
    r#"            -- BEGIN RUST GENERATED RECONCILE RECEIPT GUARD
            if not ValidateEvolutionReceipt(row.LeaderType, row) then
                Finish(owner, "TITLE_PAYMENT_PENDING");
            else
            -- END RUST GENERATED RECONCILE RECEIPT GUARD
"#
}

pub fn reconcile_close_source() -> &'static str {
    r#"            -- BEGIN RUST GENERATED RECONCILE RECEIPT GUARD CLOSE
            end
            -- END RUST GENERATED RECONCILE RECEIPT GUARD CLOSE
"#
}

pub fn source() -> &'static str {
    r#"-- BEGIN RUST GENERATED PERSONA FINALIZATION
-- Generated by civ6-native-bridge-rs::persona_finalization; edit its Rust source.
local function ValidateEvolutionReceipt(leader, row)
    -- GameInfo defines the price. Saved fields are a prepare receipt, never
    -- authority to reduce it. Validate before the UI reader, which also reads
    -- the saved cost to select its ordered native payment-promotion prefix.
    local cost = row.EvolutionCost;
    local savedCost = Get(leader, "EVOLUTION_COST");
    local surcharge = Get(leader, "EVOLUTION_SURCHARGE");
    if type(cost) ~= "number" or cost % 1 ~= 0 or cost < 1 or cost > 3 or
       type(savedCost) ~= "number" or savedCost ~= cost or
       type(surcharge) ~= "number" or surcharge % 1 ~= 0 or surcharge ~= cost - 1 then
        return nil;
    end
    return cost;
end

local function CompleteEvolution(owner, leader)
    local p, row = Player(owner, true), Definition(leader);
    if not p or not row or Get(leader, "OWNER") ~= owner then return Finish(owner, "NOT_OWNED"); end
    if Get(leader, "STATE") == "GOVERNOR" then return Finish(owner, "ALREADY_EVOLVED"); end
    if Get(leader, "STATE") ~= "EVOLVING" then return Finish(owner, "NOT_EVOLVING"); end
    local cost = ValidateEvolutionReceipt(leader, row);
    if not cost then return Finish(owner, "TITLE_PAYMENT_PENDING"); end
    local native = NativeGovernor(owner, row);
    if type(native) ~= "table" or native.appointed ~= true or native.base ~= true then
        return Finish(owner, "APPOINTMENT_PENDING");
    end
    -- Unknown payment is not zero, including cost-one people. Normal prepare
    -- writes an explicit zero; no implicit legacy receipt migration is proven.
    if type(native.surchargePaid) ~= "number" or native.surchargePaid % 1 ~= 0 or
       native.surchargePaid ~= cost - 1 then
        return Finish(owner, "TITLE_PAYMENT_PENDING");
    end
    -- Retain the Great Person until the engine has really appointed its Governor.
    local unit, ready = FindPerson(owner, row);
    if not ready then return Finish(owner, "REMOVAL_PENDING"); end
    if leader == ASHINA_ADMISSION then SyncAshinaAdmission(true); end
    SyncProductionAdmission(true, owner);
    if unit then p:GetUnits():Destroy(unit); end -- TunerMapPanel.lua:199, also accepts no return value
    local remaining, observed = FindPerson(owner, row);
    if remaining or not observed then return Finish(owner, "REMOVAL_PENDING"); end
    Set(leader, "UNIT", nil);
    Set(leader, "STATE", "GOVERNOR");
    if leader == ASHINA_ADMISSION then SyncAshinaAdmission(false); end
    SyncProductionAdmission(false, owner);
    SnapshotAlliances(owner, leader);
    return Finish(owner, "EVOLVED");
end
-- END RUST GENERATED PERSONA FINALIZATION

"#
}

/// Migrate the legacy function or regenerate its marked block, preserving every
/// byte outside the completion block and two reconciliation guard snippets.
pub fn regenerate(text: &str) -> Result<String, &'static str> {
    if text.matches(FUNCTION).count() != 1 || text.matches(NEXT).count() != 1 {
        return Err("expected unique CompleteEvolution and Reconcile boundaries");
    }
    let function = text.find(FUNCTION).ok_or("completion function missing")?;
    let finish = text.find(NEXT).ok_or("reconciliation boundary missing")?;
    if finish <= function {
        return Err("reconciliation precedes completion");
    }
    let start = if text.contains(BEGIN) || text.contains(END) {
        if text.matches(BEGIN).count() != 1 || text.matches(END).count() != 1 {
            return Err("ambiguous generated markers");
        }
        let start = text.find(BEGIN).ok_or("generated start missing")?;
        let end = text.find(END).ok_or("generated end missing")?;
        if start > function
            || end < function
            || end >= finish
            || !text[end + END.len()..finish].trim().is_empty()
        {
            return Err("generated markers cross function boundaries");
        }
        start
    } else {
        function
    };
    let generated = if text[start..finish].contains("\r\n") {
        source().replace('\n', "\r\n")
    } else {
        source().to_owned()
    };
    let completion = format!("{}{}{}", &text[..start], generated, &text[finish..]);
    regenerate_reconcile(&completion)
}

fn regenerate_reconcile(text: &str) -> Result<String, &'static str> {
    let start = text.find(NEXT).ok_or("reconciliation missing")?;
    if text.matches(AFTER_RECONCILE).count() != 1 {
        return Err("expected unique reconciliation end boundary");
    }
    let finish = text
        .find(AFTER_RECONCILE)
        .ok_or("reconciliation end missing")?;
    if finish <= start {
        return Err("reversed reconciliation boundary");
    }
    let original = &text[start..finish];
    let mut block = original.replace("\r\n", "\n");
    if block.matches(reconcile_open_source()).count()
        != block.matches(reconcile_close_source()).count()
    {
        return Err("unpaired reconciliation guard");
    }
    // Strip only exact snippets we own; unexpected edits fail rather than
    // rewriting the native reads, missing-person handling or callbacks.
    for snippet in [reconcile_open_source(), reconcile_close_source()] {
        if block.matches(snippet).count() > 1 {
            return Err("duplicate reconciliation guard");
        }
        block = block.replacen(snippet, "", 1);
    }
    if block.contains("RUST GENERATED RECONCILE RECEIPT GUARD")
        || block.matches(READ).count() != 1
        || block.matches(TAIL).count() != 1
    {
        return Err("unexpected reconciliation guard or anchors");
    }
    block = block.replacen(READ, &(reconcile_open_source().to_owned() + READ), 1);
    block = block.replacen(TAIL, &(reconcile_close_source().to_owned() + TAIL), 1);
    if original.contains("\r\n") {
        block = block.replace('\n', "\r\n");
    }
    Ok(format!("{}{}{}", &text[..start], block, &text[finish..]))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shipped_completion_is_exact_generated_source() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let text = std::fs::read_to_string(
            root.join("poc/JAC_PoC_LeaderPersona/Scripts/JAC_LeaderPersona_Gameplay.lua"),
        )
        .unwrap();
        assert_eq!(text, regenerate(&text).unwrap());
        let normalized = text.replace("\r\n", "\n");
        let start = normalized.find(BEGIN).unwrap();
        let finish = normalized.find(NEXT).unwrap();
        assert_eq!(&normalized[start..finish], source());
        assert_eq!(normalized.matches(reconcile_open_source()).count(), 1);
        assert_eq!(normalized.matches(reconcile_close_source()).count(), 1);
    }

    #[test]
    fn migration_preserves_surroundings_and_regeneration_is_idempotent() {
        for newline in ["\n", "\r\n"] {
            let prefix = format!("-- unrelated appointment, paid, merit bytes{newline}");
            let reconcile = format!("{NEXT}\n    for row in rows() do\n        if pending then\n{READ}\n            -- existing native handling\n{TAIL}");
            let suffix = format!("{AFTER_RECONCILE} return 0; end\n-- existing callbacks\n");
            let input = format!(
                "{prefix}{}",
                format!("{FUNCTION}\n    return 0;\nend\n\n{reconcile}{suffix}")
                    .replace('\n', newline)
            );
            let output = regenerate(&input).unwrap();
            let expected_reconcile = reconcile
                .replace(READ, &(reconcile_open_source().to_owned() + READ))
                .replace(TAIL, &(reconcile_close_source().to_owned() + TAIL));
            assert_eq!(
                output,
                format!(
                    "{prefix}{}",
                    format!("{}{expected_reconcile}{suffix}", source()).replace('\n', newline)
                )
            );
            assert_eq!(output, regenerate(&output).unwrap());
        }
    }

    #[test]
    fn ambiguous_or_reversed_boundaries_are_rejected() {
        for text in [
            format!("{FUNCTION}\n{FUNCTION}\n{NEXT}"),
            format!("{NEXT}\n{FUNCTION}"),
            format!("{BEGIN}\n{FUNCTION}\n{NEXT}"),
            format!("{FUNCTION}\n{NEXT}\n{END}"),
            format!("{BEGIN}\n{FUNCTION}\n{END}\nforeign code\n{NEXT}"),
        ] {
            assert!(
                regenerate(&text).is_err(),
                "accepted ambiguous input: {text}"
            );
        }
    }

    #[test]
    fn guard_transform_rejects_drift_without_rewriting_existing_reconciliation() {
        let valid = format!("{NEXT}\n{READ}\n{TAIL}{AFTER_RECONCILE}");
        for invalid in [
            valid.replace(READ, "changed native read"),
            valid.replace(READ, &format!("{READ}\n{READ}")),
            valid.replace(TAIL, "changed tail"),
            valid.replace(READ, &(reconcile_open_source().to_owned() + READ)),
            valid.replace(
                READ,
                &format!("-- RUST GENERATED RECONCILE RECEIPT GUARD edited\n{READ}"),
            ),
        ] {
            assert!(regenerate_reconcile(&invalid).is_err());
        }
    }
}
