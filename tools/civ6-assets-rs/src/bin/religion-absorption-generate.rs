use std::path::PathBuf;

// The checked-in Lua is a Civ6 VFS artifact. Change this Rust source, then run
// `cargo run --locked -p civ6-assets-rs --bin religion-absorption-generate`.
const LUA: &str = r#"-- Generated by tools/civ6-assets-rs/src/bin/religion-absorption-generate.rs.
-- Both RP and absorption are included in this Gameplay context by the entry.
local RP = assert(JAC_ReligionPersistenceGameplay, "RP Gameplay must load in this context")
local KEY, NAME = "JAC_RP_STATE_V1", "religion-persistence"

local function copy(value)
  if type(value) ~= "table" then return value end
  local out = {}
  for k, v in pairs(value) do out[k] = copy(v) end
  return out
end

local function equal(a, b)
  if type(a) ~= type(b) then return false end
  if type(a) ~= "table" then return a == b end
  for k, v in pairs(a) do if not equal(v, b[k]) then return false end end
  for k in pairs(b) do if a[k] == nil then return false end end
  return true
end

local function requireState()
  local state = RP.Export() -- a copy, including V1 legacy normalization
  assert(state.schema == 1 and type(state.religions) == "table"
    and type(state.heroes) == "table" and type(state.artifacts) == "table",
    "unsupported RP save")
  assert(type(state.revision) == "number" and state.revision >= 0
    and state.revision <= 2147483647 and state.revision == math.floor(state.revision),
    "unsupported RP revision")
  assert(state.absorptionReceipts == nil or type(state.absorptionReceipts) == "table",
    "damaged RP absorption receipts")
  return state
end

local function holderAfter(holder, from, to)
  if type(holder) ~= "string" then return holder end
  for _, prefix in ipairs({ "PLAYER_", "HIDDEN_PLAYER_", "VAULT_PLAYER_", "HERO_PLAYER_" }) do
    if holder == prefix .. from then return prefix .. to end
  end
  return holder -- cave, site, person and third-party holders retain their identity
end

local function relevant(religion, from)
  if religion.founder == from then return true end
  for _, c in pairs(religion.communities) do
    if c.holder == "PLAYER_" .. from then return true end
  end
  for _, a in pairs(religion.assets) do
    if a.owner == from or holderAfter(a.holder, from, "") ~= a.holder then return true end
  end
  for _, d in pairs(religion.discoveries) do
    if d.player == from and d.outcome == nil then return true end
  end
  for _, v in pairs(religion.revivals) do
    if v.holder == "PLAYER_" .. from then return true end
  end
  return false
end

local function heroSnapshot(state, tx)
  local from, to = tostring(tx.From), tostring(tx.To)
  local hero = state.heroes[from]
  if not hero then return nil end
  assert(state.heroes[to] == nil, "RP destination hero slot occupied")
  assert(hero.verification == "APPLIED", "RP hero reward pending")
  assert(type(hero.unit) == "number", "RP hero unit missing")
  local found
  for _, unit in ipairs(tx.Units or {}) do
    if unit.ID == hero.unit then
      assert(found == nil, "duplicate RP hero source unit")
      found = unit
    end
  end
  assert(found and found.Hero and found.KeepUnit and found.Destination == tx.To
    and found.Outcome ~= "SUICIDE", "RP hero must transfer with its native unit")
  assert(hero.heroClass == found.Hero.Class and hero.heroUnit == found.Type,
    "RP hero native identity mismatch")
  return hero.unit
end

local function inspect(state, tx)
  local from = tx.From
  local touched = {}
  for id, religion in pairs(state.religions) do
    assert(type(religion.communities) == "table" and type(religion.assets) == "table"
      and type(religion.discoveries) == "table" and type(religion.revivals) == "table",
      "damaged RP religion " .. tostring(id))
    for _, d in pairs(religion.discoveries) do
      assert(d.player ~= from or d.effects ~= "PENDING", "RP discovery effect pending")
    end
    for _, use in pairs(religion.materialUses or {}) do
      assert(use.player ~= from or use.effects ~= "PENDING", "RP material effect pending")
    end
    for _, revival in pairs(religion.revivals) do
      assert(revival.player ~= from or revival.effects ~= "PENDING", "RP revival effect pending")
    end
    if relevant(religion, from) then
      touched[id] = true
      for _, d in pairs(religion.discoveries) do
        assert(d.effects ~= "PENDING", "RP discovery effect pending")
      end
      for _, use in pairs(religion.materialUses or {}) do
        assert(use.effects ~= "PENDING", "RP material effect pending")
      end
      for _, revival in pairs(religion.revivals) do
        assert(revival.effects ~= "PENDING", "RP revival effect pending")
      end
    end
  end
  local fromKey, toKey = tostring(from), tostring(tx.To)
  if state.artifacts[fromKey] then
    assert(state.artifacts[toKey] == nil, "RP destination Vault slot occupied")
  end
  return touched, heroSnapshot(state, tx)
end

local function projection(religion)
  local result = copy(religion)
  -- Native followers and their derived labels can change between turns. Their
  -- current values are read by RP, never frozen in an absorption receipt.
  result.followers, result.publicFacilities, result.lost = nil, nil, nil
  result.underground, result.state, result.canRevive = nil, nil, nil
  return result
end

local function verifyReceipt(state, tx, snapshot, receipt)
  assert(receipt.ID == tx.ID and receipt.From == tx.From and receipt.To == tx.To
    and receipt.Version == 1 and type(receipt.Revision) == "number"
    and state.revision >= receipt.Revision, "RP absorption receipt mismatch")
  local fromKey, toKey = tostring(tx.From), tostring(tx.To)
  assert(state.heroes[fromKey] == nil and state.artifacts[fromKey] == nil,
    "RP source player slot survived absorption")
  if receipt.Hero then
    assert(equal(state.heroes[toKey], receipt.Hero), "RP hero transfer mismatch")
  end
  if receipt.Artifact then
    assert(equal(state.artifacts[toKey], receipt.Artifact), "RP Vault transfer mismatch")
  end
  for id, expected in pairs(receipt.Religions) do
    local current = assert(state.religions[id], "RP religion disappeared")
    assert(current.founder == expected.founder
      and current.engineReligion == expected.engineReligion,
      "RP founder or native religion changed")
    if current.founder == tx.From then
      assert(current.founderDefeated == true, "RP founder defeat missing")
    end
    -- Later RP actions can add communities, discoveries and revival receipts
    -- even in this turn. Exact comparison applies only before their commits.
    if state.revision == receipt.Revision then
      assert(equal(projection(current), expected), "RP religion transfer mismatch")
    end
  end
  if snapshot.HeroUnit then
    local map = assert((tx.UnitMap or {})[fromKey .. ":" .. snapshot.HeroUnit],
      "RP hero unit mapping lost")
    assert(receipt.Hero and receipt.Hero.unit == map.ID, "RP hero mapping mismatch")
  end
end

local Adapter = {}

function Adapter.Prepare(tx)
  assert(type(tx.ID) == "string" and type(tx.From) == "number"
    and type(tx.To) == "number" and tx.From ~= tx.To, "invalid RP absorption transaction")
  local state = requireState()
  assert(state.revision < 2147483647, "RP revision has no increment capacity")
  assert(not state.absorptionReceipts or state.absorptionReceipts[tx.ID] == nil,
    "RP absorption receipt ID already used")
  inspect(state, tx) -- read-only; no reservation or property write
  return { Version = 1, From = tx.From, To = tx.To,
    HeroUnit = state.heroes[tostring(tx.From)] and state.heroes[tostring(tx.From)].unit,
    Empty = Game:GetProperty(KEY) == nil }
end

function Adapter.Apply(tx, snapshot)
  assert(snapshot.Version == 1 and snapshot.From == tx.From and snapshot.To == tx.To,
    "RP absorption snapshot mismatch")
  local state = requireState() -- fresh state: preserve RP changes made after Prepare
  state.absorptionReceipts = state.absorptionReceipts or {}
  local receipt = state.absorptionReceipts[tx.ID]
  if receipt then
    verifyReceipt(state, tx, snapshot, receipt)
    return -- a successful property write already included the receipt
  end
  assert(state.revision < 2147483647, "RP revision has no increment capacity")
  local touched, sourceHero = inspect(state, tx)
  assert(sourceHero == snapshot.HeroUnit, "RP source hero changed after preparation")
  local fromKey, toKey = tostring(tx.From), tostring(tx.To)
  for id in pairs(touched) do
    local religion = state.religions[id]
    if religion.founder == tx.From then religion.founderDefeated = true end
    for _, c in pairs(religion.communities) do
      c.holder = holderAfter(c.holder, fromKey, toKey)
    end
    for _, asset in pairs(religion.assets) do
      if asset.owner == tx.From then asset.owner = tx.To end
      asset.holder = holderAfter(asset.holder, fromKey, toKey)
    end
    for _, d in pairs(religion.discoveries) do
      -- APPLIED discoveries and their effect/player history remain attributed
      -- to the original actor. Only an unresolved choice changes hands.
      if d.outcome == nil and d.player == tx.From then
        d.player = tx.To
        d.actor = holderAfter(d.actor, fromKey, toKey)
      end
    end
    for _, revival in pairs(religion.revivals) do
      revival.holder = holderAfter(revival.holder, fromKey, toKey)
    end
  end
  if sourceHero then
    local mapped = assert((tx.UnitMap or {})[fromKey .. ":" .. sourceHero],
      "RP hero unit mapping missing")
    assert(type(mapped.ID) == "number", "RP hero replacement ID missing")
    local hero = state.heroes[fromKey]
    hero.unit = mapped.ID
    state.heroes[toKey], state.heroes[fromKey] = hero, nil
  end
  if state.artifacts[fromKey] then
    state.artifacts[toKey], state.artifacts[fromKey] = state.artifacts[fromKey], nil
  end
  state.revision = state.revision + 1
  receipt = { Version = 1, ID = tx.ID, From = tx.From, To = tx.To,
    Turn = Game.GetCurrentGameTurn(), Revision = state.revision, Religions = {},
    Hero = copy(state.heroes[toKey]), Artifact = copy(state.artifacts[toKey]) }
  for id in pairs(touched) do receipt.Religions[id] = projection(state.religions[id]) end
  state.absorptionReceipts[tx.ID] = receipt
  Game:SetProperty(KEY, state) -- one write contains every patch and its retry receipt
end

function Adapter.Verify(tx, snapshot)
  assert(snapshot.Version == 1 and snapshot.From == tx.From and snapshot.To == tx.To,
    "RP absorption snapshot mismatch")
  local state = requireState()
  local receipt = assert((state.absorptionReceipts or {})[tx.ID],
    "RP absorption receipt missing")
  verifyReceipt(state, tx, snapshot, receipt)
end

JAC_RP_AbsorptionAdapter = Adapter
"#;

fn target() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../poc/JAC_PoC_ReligionPersistence/Scripts/JAC_RP_AbsorptionAdapter.lua")
}

fn main() -> std::io::Result<()> {
    let path = target();
    if std::env::args().any(|arg| arg == "--check") {
        if std::fs::read_to_string(path)? != LUA {
            return Err(std::io::Error::other("RP absorption Lua is out of date"));
        }
    } else {
        std::fs::write(path, LUA)?;
    }
    Ok(())
}

