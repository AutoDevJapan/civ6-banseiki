fn artdef(people: &[Person], template: &str, element: &str) -> String {
    let mut out = ARTDEF_HEAD.replace("{GENERATED}", GENERATED);
    out = out.replace("{TEMPLATE}", template);
    for p in people.iter().filter(|p| !p.existing) {
        out.push_str(&element.replace("{LEADER}", &p.leader));
    }
    out.push_str(ARTDEF_TAIL);
    out
}

/// (path relative to the repository root, contents) of every generated file.
pub fn outputs() -> Result<Vec<(PathBuf, String)>> {
    let people = people()?;
    let dir = PathBuf::from(MOD_DIR);
    let leaders = artdef(&people, "Leaders", LEADER_ELEMENT);
    let fallback = artdef(&people, "LeaderFallback", FALLBACK_ELEMENT);
    Ok(vec![
        (
            dir.join("Config/JAC_BanseikiPool_Config.sql"),
            config_sql(&people),
        ),
        (
            dir.join("Data/JAC_BanseikiPool_Gameplay.sql"),
            gameplay_sql(&people),
        ),
        (
            dir.join("Text/JAC_BanseikiPool_Text.xml"),
            text_xml(&people)?,
        ),
        (
            dir.join("Data/JAC_BanseikiPool_Icons.xml"),
            icons_xml(&people),
        ),
        (
            dir.join("Data/JAC_BanseikiPool_Colors.xml"),
            colors_xml(&people),
        ),
        (dir.join("ArtDefs/Leaders.artdef"), leaders),
        (dir.join("ArtDefs/FallbackLeaders.artdef"), fallback),
    ])
}

/// Write the generated files, or with `check` only compare them.
pub fn run(check: bool) -> Result<()> {
    let mut stale = Vec::new();
    for (path, text) in outputs()? {
        let full = root().join(&path);
        if !check {
            crate::write(&full, text)?;
        } else if std::fs::read_to_string(&full).ok().as_deref() != Some(text.as_str()) {
            stale.push(path.display().to_string());
        }
    }
    let stale = stale.join(", ");
    ensure!(
        stale.is_empty(),
        "out of date (run banseiki-pool-generate): {stale}"
    );
    Ok(())
}
