/// Latin transliteration of the kana reading, used as the EN/RU name. It is not a
/// translation: long vowels are spelt out (もうり -> Mouri) and no macrons are used.
pub fn romanize(reading: &str) -> Result<String> {
    let mut words = vec![String::new()];
    let mut previous = "";
    let mut double = false;
    for c in reading.chars() {
        if matches!(c, ' ' | '　' | '・') {
            words.push(String::new());
            previous = "";
            continue;
        }
        let c = match c {
            'ァ'..='ヶ' => char::from_u32(c as u32 - 0x60).unwrap(),
            _ => c,
        };
        let word = words.last_mut().unwrap();
        if c == 'っ' {
            double = true;
            continue;
        }
        if c == 'ー' {
            if let Some(v) = previous.chars().rev().find(|v| "aeiou".contains(*v)) {
                word.push(v);
            }
            continue;
        }
        let syllable = kana(c).with_context(|| format!("not kana: {c} in {reading}"))?;
        let small_y = matches!(c, 'ゃ' | 'ゅ' | 'ょ');
        let small_v = matches!(c, 'ぁ' | 'ぃ' | 'ぅ' | 'ぇ' | 'ぉ');
        if small_y && previous.len() > 1 && previous.ends_with('i') {
            word.pop();
            let palatal = ["shi", "chi", "ji"].contains(&previous);
            word.push_str(if palatal { &syllable[1..] } else { syllable });
        } else if small_v && !previous.is_empty() {
            word.pop();
            if previous == "u" {
                word.push('w');
            }
            word.push_str(syllable);
        } else {
            if double && syllable.starts_with("ch") {
                word.push('t');
            } else if double && !"aeioun".contains(&syllable[..1]) {
                word.push_str(&syllable[..1]);
            }
            word.push_str(syllable);
        }
        double = false;
        previous = syllable;
    }
    let mut out = Vec::new();
    for word in words.iter().filter(|w| !w.is_empty()) {
        let mut chars = word.chars();
        let first = chars.next().unwrap().to_ascii_uppercase();
        out.push(format!("{first}{}", chars.as_str()));
    }
    ensure!(!out.is_empty(), "empty reading");
    Ok(out.join(" "))
}

fn sql(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

fn esc(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// `<count>:<sha256 prefix>` of the PersonID -> LeaderType ledger, stored in each save.
pub fn ledger_version(people: &[Person]) -> String {
    let mut lines = String::new();
    for p in people {
        lines.push_str(&format!("{}\t{}\n", p.id, p.leader));
    }
    format!("{}:{}", people.len(), &sha256(lines.as_bytes())[..16])
}

