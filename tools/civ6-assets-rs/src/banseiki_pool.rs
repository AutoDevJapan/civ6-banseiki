fn pool_rows(people: &[Person]) -> String {
    let mut values = Vec::new();
    for (i, p) in people.iter().enumerate() {
        let fields = [
            sql(&p.id),
            sql(&p.leader),
            sql(&p.civ),
            sql(&p.source),
            u8::from(!p.existing).to_string(),
            sql(&p.name),
            sql(&p.reading),
            sql(&p.era),
            sql(&p.region),
            sql(&p.faction),
            sql(&p.category),
            sql(&p.trait_ja),
            sql(&p.trait_type()),
            sql(&p.origin),
            sql(&p.background),
            (i + 1).to_string(),
        ];
        values.push(format!("\t({})", fields.join(", ")));
    }
    format!("{POOL_TABLE}{};\n", values.join(",\n"))
}

