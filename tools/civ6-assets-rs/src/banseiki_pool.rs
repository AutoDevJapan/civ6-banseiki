/// LeaderType -> (CivilizationType, PortraitBackground) of the 22 existing 1534 leaders.
fn seats() -> Result<BTreeMap<String, (String, String)>> {
    let mut out = BTreeMap::new();
    for file in ["JAC_CustomCivs_Players.xml", "JAC_Japan1534_Players.xml"] {
        let doc = xml(root().join(CUSTOM_CIVS).join("Config").join(file))?;
        for row in rows(&doc, "Players") {
            ensure!(attr(row, "Domain") == DOMAIN, "{file}: unexpected domain");
            let civ = attr(row, "CivilizationType").to_owned();
            let background = attr(row, "PortraitBackground").to_owned();
            out.insert(attr(row, "LeaderType").to_owned(), (civ, background));
        }
    }
    Ok(out)
}

/// CivilizationType -> Japanese name of the existing houses, read from the CustomCivs text.
fn civ_names() -> Result<BTreeMap<String, String>> {
    let mut out = BTreeMap::new();
    for file in ["JAC_CustomCivs_Text.xml", "JAC_Japan1534_Text.xml"] {
        let doc = xml(root().join(CUSTOM_CIVS).join("Text").join(file))?;
        for row in rows(&doc, "LocalizedText") {
            let civ = attr(row, "Tag").strip_prefix("LOC_").unwrap_or("");
            let civ = civ.strip_suffix("_NAME").unwrap_or("");
            if civ.starts_with("CIVILIZATION_JAC_") && attr(row, "Language") == "ja_JP" {
                out.insert(civ.to_owned(), text_of(row, "Text"));
            }
        }
    }
    Ok(out)
}

/// (LeaderType, CivilizationType, source leader, background texture, existing).
type Placement = (String, String, String, String, bool);

fn placement(
    row: &Value,
    seats: &BTreeMap<String, (String, String)>,
    names: &BTreeMap<String, String>,
) -> Result<Placement> {
    let id = s(&row["id"]);
    if let Some(existing) = row["existing_leader_id"].as_str() {
        let seat = seats.get(existing);
        let (civ, background) = seat.with_context(|| format!("{id}: {existing} is not 1534"))?;
        let leader = existing.to_owned();
        return Ok((
            leader.clone(),
            civ.clone(),
            leader,
            background.clone(),
            true,
        ));
    }
    let leader = format!("LEADER_{id}");
    // A fictional retainer of one of the existing houses joins that house's civilization;
    // no new house civilization is ever created here.
    if let Some(house) = s(&row["faction"]).strip_suffix(HOUSE_SUFFIX) {
        let mut found = Vec::new();
        for (source, (civ, background)) in seats {
            let name = names.get(civ).map(String::as_str).unwrap_or("");
            if name == house || format!("{name}家") == house {
                found.push((source, civ, background));
            }
        }
        ensure!(
            found.len() == 1,
            "{id}: {house} is not exactly one existing house"
        );
        let (source, civ, background) = found[0];
        return Ok((
            leader,
            civ.clone(),
            source.clone(),
            background.clone(),
            false,
        ));
    }
    let region = s(&row["region"]);
    let found = REGIONS.iter().find(|r| r.0 == region);
    let &(_, _, _, civ, source) = found.with_context(|| format!("{id}: no region {region}"))?;
    let background = format!("{source}_BACKGROUND");
    Ok((leader, civ.to_owned(), source.to_owned(), background, false))
}

pub fn people() -> Result<Vec<Person>> {
    let data = read_json(root().join(civ6_data_rs::pool::DATA_PATH))?;
    civ6_data_rs::pool::validate(&data)?;
    let seats = seats()?;
    let names = civ_names()?;
    let mut people = Vec::new();
    let mut leaders = BTreeSet::new();
    for row in data["characters"].as_array().context("characters")? {
        if row["leader_candidate"] != true {
            continue;
        }
        let id = s(&row["id"]).to_owned();
        let (leader, civ, source, background, existing) = placement(row, &seats, &names)?;
        ensure!(
            leaders.insert(leader.clone()),
            "{leader} is registered twice"
        );
        let trait_ja = s(&row["trait"]).to_owned();
        let found = TRAITS.iter().find(|t| t.0 == trait_ja);
        let trait_key = found
            .with_context(|| format!("{id}: unknown trait {trait_ja}"))?
            .1;
        people.push(Person {
            id,
            leader,
            civ,
            source,
            background,
            existing,
            name: s(&row["name"]).to_owned(),
            reading: s(&row["reading"]).to_owned(),
            era: s(&row["era"]).to_owned(),
            region: s(&row["region"]).to_owned(),
            faction: s(&row["faction"]).to_owned(),
            category: s(&row["category"]).to_owned(),
            trait_ja,
            trait_key,
            origin: s(&row["origin"]).to_owned(),
            description: s(&row["description"]).to_owned(),
        });
    }
    Ok(people)
}

