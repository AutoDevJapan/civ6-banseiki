pub fn gameplay_sql(people: &[Person]) -> String {
    let mut types = Vec::new();
    let mut traits = Vec::new();
    for (_, key, _, _) in TRAITS {
        let name = format!("TRAIT_LEADER_JAC_POOL_{key}");
        types.push(format!("\t('{name}', 'KIND_TRAIT')"));
        let text = format!("'LOC_{name}_NAME', 'LOC_TRAIT_LEADER_JAC_POOL_DESCRIPTION'");
        traits.push(format!("\t('{name}', {text})"));
    }
    GAMEPLAY_SQL
        .replace("{GENERATED}", GENERATED)
        .replace("{VERSION}", &sql(&ledger_version(people)))
        .replace("{COUNT}", &people.len().to_string())
        .replace("{TRAIT_TYPES}", &types.join(",\n"))
        .replace("{TRAITS}", &traits.join(",\n"))
        .replace("{ROWS}", &pool_rows(people))
}

fn head(root: &str) -> String {
    format!("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- {GENERATED}. -->\n<{root}>\n")
}

fn text_row(out: &mut String, tag: &str, language: &str, text: &str) {
    out.push_str(&format!(
        "\t\t<Row Tag=\"{tag}\" Language=\"{language}\">\n"
    ));
    out.push_str(&format!("\t\t\t<Text>{}</Text>\n\t\t</Row>\n", esc(text)));
}

fn label(
    table: &[(&'static str, &'static str, &'static str)],
    key: &str,
) -> Result<[&'static str; 2]> {
    let row = table.iter().find(|r| r.0 == key);
    let row = row.with_context(|| format!("no EN/RU label for {key}"))?;
    Ok([row.1, row.2])
}

pub fn text_xml(people: &[Person]) -> Result<String> {
    let mut out = head("GameData");
    out.push_str("\t<LocalizedText>\n");
    for (ja, key, en, ru) in TRAITS {
        let tag = format!("LOC_TRAIT_LEADER_JAC_POOL_{key}_NAME");
        text_row(&mut out, &tag, "ja_JP", ja);
        text_row(&mut out, &tag, "en_US", en);
        text_row(&mut out, &tag, "ru_RU", ru);
    }
    let tag = "LOC_TRAIT_LEADER_JAC_POOL_DESCRIPTION";
    text_row(
        &mut out,
        tag,
        "ja_JP",
        "万世紀プールの特性（PoC）。ゲーム上の効果はまだ無い。",
    );
    text_row(
        &mut out,
        tag,
        "en_US",
        "Banseiki pool trait (PoC). No gameplay effect yet.",
    );
    text_row(
        &mut out,
        tag,
        "ru_RU",
        "Черта пула Бансэйки (PoC). Пока не влияет на игру.",
    );
    for p in people.iter().filter(|p| !p.existing) {
        let latin = romanize(&p.reading)?;
        let category = label(&CATEGORIES, &p.category)?;
        let era = label(&ERAS, &p.era)?;
        let region = REGIONS.iter().find(|r| r.0 == p.region).context("region")?;
        let region = [region.1, region.2];
        let t = TRAITS
            .iter()
            .find(|t| t.1 == p.trait_key)
            .context("trait")?;
        let trait_label = [t.2, t.3];
        let name = format!("LOC_{}_NAME", p.leader);
        text_row(&mut out, &name, "ja_JP", &p.name);
        text_row(&mut out, &name, "en_US", &latin);
        text_row(&mut out, &name, "ru_RU", &latin);
        let profile = format!("LOC_{}_PROFILE", p.leader);
        let head = format!("{}（{}）", p.name, p.reading);
        let tags = [&p.category, &p.trait_ja, &p.era, &p.region].map(String::as_str);
        let tags = tags.join("／");
        let tail = format!("{}[NEWLINE][NEWLINE]{}", p.faction, p.description);
        let ja = format!("{head}[NEWLINE]{tags}[NEWLINE]{tail}");
        text_row(&mut out, &profile, "ja_JP", &ja);
        for (i, (language, note)) in [("en_US", EN_NOTE), ("ru_RU", RU_NOTE)].iter().enumerate() {
            let tags = [category[i], trait_label[i], era[i], region[i]].join(" / ");
            let text = format!("{latin}[NEWLINE]{tags}[NEWLINE]{note}");
            text_row(&mut out, &profile, language, &text);
        }
    }
    out.push_str("\t</LocalizedText>\n</GameData>\n");
    Ok(out)
}

pub fn icons_xml(people: &[Person]) -> String {
    let mut out = head("GameInfo");
    out.push_str("\t<!-- No portrait exists yet: every new leader uses the official generic\n");
    out.push_str("\t     leader icon (ICON_LEADER_DEFAULT, Base Icons_Leaders.xml). -->\n");
    out.push_str("\t<IconDefinitions>\n");
    for p in people.iter().filter(|p| !p.existing) {
        let name = format!("ICON_{}", p.leader);
        let row = format!("\t\t<Row Name=\"{name}\" Atlas=\"ICON_ATLAS_LEADERS\" Index=\"0\"/>\n");
        out.push_str(&row);
    }
    out.push_str("\t</IconDefinitions>\n</GameInfo>\n");
    out
}

const COLOR_ROW: &str = "\t\t<Row>
			<Type>{T}</Type><Usage>Unique</Usage>
			<PrimaryColor>{A}</PrimaryColor><SecondaryColor>{B}</SecondaryColor>
			<Alt1PrimaryColor>{B}</Alt1PrimaryColor><Alt1SecondaryColor>{A}</Alt1SecondaryColor>
			<Alt2PrimaryColor>{C}</Alt2PrimaryColor><Alt2SecondaryColor>{D}</Alt2SecondaryColor>
			<Alt3PrimaryColor>{D}</Alt3PrimaryColor><Alt3SecondaryColor>{C}</Alt3SecondaryColor>
		</Row>
";

pub fn colors_xml(people: &[Person]) -> String {
    let mut out = head("GameInfo");
    out.push_str("\t<PlayerColors>\n");
    for (i, p) in people.iter().filter(|p| !p.existing).enumerate() {
        let (a, b) = PALETTE[i % PALETTE.len()];
        let (c, d) = PALETTE[(i + 1) % PALETTE.len()];
        let row = COLOR_ROW.replace("{A}", a).replace("{B}", b);
        let row = row.replace("{C}", c).replace("{D}", d);
        out.push_str(&row.replace("{T}", &p.leader));
    }
    out.push_str("\t</PlayerColors>\n</GameInfo>\n");
    out
}

