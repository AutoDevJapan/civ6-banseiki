def _base() -> tuple[dict, dict]:
    base = json.loads((SCENARIOS / "japan-map-15km.json").read_text(encoding="utf-8"))
    setup = json.loads((SCENARIOS / "sengoku-trees.json").read_text(encoding="utf-8"))
    return base, setup


def _setup_step(setup: dict, second_leader: str) -> dict:
    step = dict(setup["steps"][2])
    step["code"] = step["code"].replace("LEADER_JAC_TAKEDA_NOBUTORA", second_leader)
    return step


HUMAN = 0  # configure puts the human Oda in slot 0 (checked by the HostGame step)


def _castle_lua(rows: list[tuple[int, int, int]]) -> str:
    """Lua prelude: castle(city) is true for a city standing on a registered plot."""
    keys = ",".join(f"['{x},{y}']=true" for x, y, _ in rows)
    return (f"local plots={{{keys}}}; "
            "local function castle(city) return plots[city:GetX()..','..city:GetY()]==true end; ")


def _tally() -> str:
    return ("local total=0; local owned=0; "
            "for _,owner in ipairs(PlayerManager.GetAliveIDs()) do "
            "for _,city in Players[owner]:GetCities():Members() do "
            "if castle(city) then total=total+1; "
            f"if owner=={HUMAN} then owned=owned+1 end end end end; ")


def _count_code(label: str, rows: list[tuple[int, int, int]], *,
                total: int | None = None, missing: int | None = None) -> str:
    """Count cities on registered plots over every alive player (majors, minors, free cities)."""
    checks = [f"total~={total}"] if total is not None else []
    checks += [f"total-owned~={missing}"] if missing is not None else []
    return (_castle_lua(rows) + _tally() +
            f"if {' or '.join(checks)} then error('{label} castles '..owned..'/'..total) end; ")


def scenario() -> dict:
    """Live check on the small test map; no mass transfers (live stall 2026-09-29)."""
    base, setup = _base()
    rows = castles(TEST_MAP)
    total = len(rows)
    if not (total >= 3 and sum(owner == HUMAN for *_, owner in rows) == total - 2):
        raise ValueError(f"Test map must leave exactly two castles to Date: {rows}")
    players = [{"leader": test_map.SEATS[test_map.SEAT_INDEX[slug]].leader,
                "civ": test_map.SEATS[test_map.SEAT_INDEX[slug]].civ, "human": slug == "ODA"}
               for slug in test_map.PLAYERS]
    initial = (
        _count_code("initial", rows, total=total, missing=2) +
        f"if not Game.IsVictoryEnabled('{VICTORY}') then error('unification victory disabled') end; "
        "if Game.GetWinningTeam()~=nil then error('winner at start') end; "
        f"return 'registered={total}, two held by Date'"
    )
    # Raze Date's non-capital castle so the condition must shrink to the survivors.
    # DestroyCity is only a GameCore export string (unverified); if it does not remove
    # the city, hand the city to Oda instead so the victory checks still run, and
    # let the wait after the last transfer fail on the castle total.
    raze = (
        _castle_lua(rows) + "local target=nil; "
        "for _,owner in ipairs(PlayerManager.GetAliveIDs()) do "
        f"if PlayerConfigurations[owner]:GetCivilizationTypeName()=='{players[1]['civ']}' then "
        "local capital=Players[owner]:GetCities():GetCapitalCity(); "
        "for _,city in Players[owner]:GetCities():Members() do "
        "if castle(city) and (not capital or city:GetID()~=capital:GetID()) "
        "then target=city end end end end; "
        "if not target then error('Date castle to raze missing') end; "
        "local owner,id=target:GetOwner(),target:GetID(); local how='DestroyCity'; "
        "if CityManager.DestroyCity then pcall(CityManager.DestroyCity,target) end; "
        "if CityManager.GetCity(owner,id) then how='fallback transfer (DestroyCity did not raze)'; "
        f"CityManager.TransferCity(CityManager.GetCity(owner,id),{HUMAN}) end; "
        "return 'raze: '..how"
    )
    negative = (
        _count_code("negative", rows, missing=1) +
        "if Game.GetWinningTeam()~=nil then error('victory with one castle missing') end; "
        "return 'negative: one castle missing ('..owned..'/'..total..'); no winner'"
    )
    final = (
        _castle_lua(rows) + "local last=nil; "
        f"for _,owner in ipairs(PlayerManager.GetAliveIDs()) do if owner~={HUMAN} then "
        "for _,city in Players[owner]:GetCities():Members() do "
        "if castle(city) then "
        "if last then error('more than one castle held out') end; last=city end end end end; "
        "if not last then error('held out castle missing') end; "
        f"CityManager.TransferCity(last,{HUMAN}); return 'transferred the last castle'"
    )
    won = (
        "local winner,v=Game.GetWinningTeam(); "
        f"return winner==Players[{HUMAN}]:GetTeam() and v~=nil and GameInfo.Victories[v]~=nil "
        f"and GameInfo.Victories[v].VictoryType=='{VICTORY}'"
    )
    # The transfer is not visible in InGame immediately (live 2026-09-29: "positive castles 2/3").
    # The transferred castle must still count: the plot, not a building, registers it.
    razed = _castle_lua(rows) + _tally() + f"return total=={total - 1} and owned==total"
    configure = {**base["steps"][1], "map_file": test_map.MAP_FILE, "map_size": test_map.MAP_SIZE,
                 "seed": 620951, "players": players}
    enable = {**base["steps"][0], "ids": [*base["steps"][0]["ids"], test_map.TEST_MOD_ID]}
    return {
        "name": "Sengoku unification victory on the test map: raze, one castle missing, save/load, then all",
        "judge_profile": "generic",
        "steps": [
            enable, configure, _setup_step(setup, players[1]["leader"]),
            {"action": "start_game", "timeout": 240},
            {"action": "ui_lua", "state_name": "InGame", "code": initial},
            {"action": "ui_lua", "state_name": "GameCore_Tuner", "code": raze},
            {"action": "ui_lua", "state_name": "InGame", "code": negative},
            {"action": "ui_lua", "state_name": "InGame", "code":
             "LuaEvents.PartialScreenHooks_OpenWorldRankings(); return true"},
            {"action": "wait_for", "condition": {"type": "lua", "state_name": "WorldRankings", "code":
             "return not ContextPtr:IsHidden()"}, "timeout": 30},
            {"action": "ui_lua", "state_name": "WorldRankings", "code":
             f"ViewGeneric('{VICTORY}'); if Controls.GenericView:IsHidden() then error('custom victory tab hidden') end; "
             "return 'World Rankings shows 天下統一 condition'"},
            {"action": "screenshot", "path": "unification-progress-negative.png"},
            {"action": "ui_lua", "state_name": "InGame", "code":
             "LuaEvents.PartialScreenHooks_CloseAllExcept('_AllTheThings'); return true"},
            {"action": "autoplay", "turns": 1, "timeout": 300},
            {"action": "ui_lua", "state_name": "InGame", "code": negative},
            {"action": "save", "name": "jac-unification-negative"},
            {"action": "exit_to_menu"},  # load runs from the main menu (live 2026-09-29)
            {"action": "load", "name": "jac-unification-negative", "timeout": 300},
            {"action": "ui_lua", "state_name": "InGame", "code": negative},
            {"action": "ui_lua", "state_name": "GameCore_Tuner", "code": final},
            {"action": "wait_for", "condition": {"type": "lua", "state_name": "InGame", "code": razed},
             "timeout": 30},
            {"action": "ui_lua", "state_name": "InGame", "code": "local human=Game.GetLocalPlayer(); AutoplayManager.SetTurns(1); AutoplayManager.SetReturnAsPlayer(human); AutoplayManager.SetObserveAsPlayer(PlayerTypes.NONE); AutoplayManager.SetActive(true); return true"},  # the game ends during this turn, so wait for the winner instead of autoplay completion (live 2026-09-29),
            {"action": "wait_for", "condition": {"type": "lua", "state_name": "InGame", "code": won},
             "timeout": 300},
            {"action": "screenshot", "path": "unification-victory.png"},
        ],
    }


def registry_scenario() -> dict:
    """Lightweight check on the real 15 km map: a city stands on every registered plot at start."""
    base, setup = _base()
    rows = castles(REAL_MAP)
    check = (
        _count_code("registry", rows, total=len(rows)) +
        f"if not Game.IsVictoryEnabled('{VICTORY}') then error('unification victory disabled') end; "
        "if Game.GetWinningTeam()~=nil then error('winner at start') end; "
        f"return 'registered={len(rows)}'"
    )
    return {
        "name": f"Sengoku unification: the 15 km historical map starts with {len(rows)} registered castles",
        "judge_profile": "generic",
        "steps": [
            base["steps"][0], base["steps"][1], _setup_step(setup, "LEADER_JAC_DATE_TANEMUNE"),
            {"action": "start_game", "timeout": 600},
            {"action": "ui_lua", "state_name": "GameCore_Tuner", "code": check},
        ],
    }


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def write_json(path: Path, value: dict) -> None:
    write(path, json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def main() -> None:
    verify_registry()
    test_map.build()
    write(OUTPUT, sql())
    for path, (tag, output) in CASTLE_FILES.items():
        write(output, castle_sql(tag, castles(path)))
    write_json(SCENARIO, scenario())
    write_json(REGISTRY_SCENARIO, registry_scenario())


if __name__ == "__main__":
    main()
