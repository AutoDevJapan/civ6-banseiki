"""Generate the Sengoku victory threshold from historical Civ6Map Cities rows."""

from __future__ import annotations

from pathlib import Path
import json
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent / "japan_map_scale"))
from registered_castles import ROOT, verify_or_stamp


OUTPUT = ROOT / "poc/JAC_PoC_SengokuTrees/Data/JAC_Sengoku_Unification.sql"
SCENARIO = ROOT / "tools/civ6-autotest/scenarios/unification-victory.json"


def sql(count: int) -> str:
    if count < 1:
        raise ValueError("A victory needs registered castles")
    return f"""-- Generated by tools/generate_unification_victory.py from the historical
-- Civ6Map Cities tables; keep the threshold synchronized with both map scales.
INSERT INTO Types (Type, Kind) VALUES ('VICTORY_JAC_SENGOKU_UNIFICATION', 'KIND_VICTORY');
INSERT INTO Victories
    (VictoryType, Name, Description, Blurb, RequirementSetId, EnabledByDefault, OneMoreTurn, Icon)
VALUES
    ('VICTORY_JAC_SENGOKU_UNIFICATION', 'LOC_VICTORY_JAC_UNIFICATION_NAME',
     'LOC_VICTORY_JAC_UNIFICATION_DESCRIPTION', 'LOC_VICTORY_JAC_UNIFICATION_BLURB',
     'JAC_UNIFICATION_VICTORY_REQUIREMENTS', 1, 0, 'ICON_VICTORY_DOMINATION');

INSERT INTO RequirementSets (RequirementSetId, RequirementSetType) VALUES
    ('JAC_UNIFICATION_VICTORY_REQUIREMENTS', 'REQUIREMENTSET_TEST_ALL'),
    ('JAC_UNIFICATION_PLAYER_REQUIREMENTS', 'REQUIREMENTSET_TEST_ALL'),
    ('JAC_UNIFICATION_CITY_REQUIREMENTS', 'REQUIREMENTSET_TEST_ALL');
INSERT INTO RequirementSetRequirements (RequirementSetId, RequirementId) VALUES
    ('JAC_UNIFICATION_VICTORY_REQUIREMENTS', 'JAC_UNIFICATION_TEAM_MEMBER'),
    ('JAC_UNIFICATION_PLAYER_REQUIREMENTS', 'JAC_UNIFICATION_CASTLE_COUNT'),
    ('JAC_UNIFICATION_CITY_REQUIREMENTS', 'JAC_UNIFICATION_CITY_MARKER');
INSERT INTO Requirements (RequirementId, RequirementType) VALUES
    ('JAC_UNIFICATION_TEAM_MEMBER', 'REQUIREMENT_COLLECTION_ANY_MET'),
    ('JAC_UNIFICATION_CASTLE_COUNT', 'REQUIREMENT_COLLECTION_COUNT_EQUALS'),
    ('JAC_UNIFICATION_CITY_MARKER', 'REQUIREMENT_CITY_HAS_BUILDING');
INSERT INTO RequirementArguments (RequirementId, Name, Value) VALUES
    ('JAC_UNIFICATION_TEAM_MEMBER', 'CollectionType', 'COLLECTION_TEAM_PLAYERS'),
    ('JAC_UNIFICATION_TEAM_MEMBER', 'RequirementSetId', 'JAC_UNIFICATION_PLAYER_REQUIREMENTS'),
    ('JAC_UNIFICATION_CASTLE_COUNT', 'CollectionType', 'COLLECTION_PLAYER_CITIES'),
    ('JAC_UNIFICATION_CASTLE_COUNT', 'RequirementSetId', 'JAC_UNIFICATION_CITY_REQUIREMENTS'),
    ('JAC_UNIFICATION_CASTLE_COUNT', 'Count', '{count}'),
    ('JAC_UNIFICATION_CITY_MARKER', 'BuildingType', 'BUILDING_JAC_REGISTERED_CASTLE');
INSERT INTO RequirementStrings (RequirementId, Context, Text) VALUES
    ('JAC_UNIFICATION_TEAM_MEMBER', 'VictoryProgress', 'LOC_VICTORY_JAC_UNIFICATION_PROGRESS');
"""


def main() -> None:
    count = verify_or_stamp()
    OUTPUT.write_text(sql(count), encoding="utf-8")
    SCENARIO.write_text(json.dumps(scenario(count), ensure_ascii=False, indent=2) + "\n",
                        encoding="utf-8")


def scenario(count: int) -> dict:
    base = json.loads((ROOT / "tools/civ6-autotest/scenarios/japan-map-15km.json").read_text(encoding="utf-8"))
    setup = json.loads((ROOT / "tools/civ6-autotest/scenarios/sengoku-trees.json").read_text(encoding="utf-8"))
    marker = "BUILDING_JAC_REGISTERED_CASTLE"
    victory = "VICTORY_JAC_SENGOKU_UNIFICATION"
    initial = (
        f"local marker=GameInfo.Buildings['{marker}']; if not marker then error('castle marker missing') end; "
        f"if not Game.IsVictoryEnabled('{victory}') then error('unification victory disabled') end; "
        "if PlayerConfigurations[0]:GetLeaderTypeName()~='LEADER_JAC_ODA_NOBUHIDE' then error('slot 0 is not Oda') end; "
        "if Game.GetWinningTeam()~=nil then error('winner at start') end; "
        "local human=0; local total=0; JAC_UNIFY_QUEUE={}; JAC_UNIFY_HELDOUT=nil; "
        "for _,owner in ipairs(PlayerManager.GetAliveIDs()) do local player=Players[owner]; "
        "if player and player:IsMajor() then for _,city in player:GetCities():Members() do "
        "if city:GetBuildings():HasBuilding(marker.Index) then total=total+1; "
        "if owner~=human then local row={owner=owner,id=city:GetID()}; "
        "if PlayerConfigurations[owner]:GetCivilizationTypeName()=='CIVILIZATION_JAC_AINU' and not JAC_UNIFY_HELDOUT "
        "then JAC_UNIFY_HELDOUT=row else table.insert(JAC_UNIFY_QUEUE,row) end end end end end end; "
        f"if total~={count} or not JAC_UNIFY_HELDOUT or #JAC_UNIFY_QUEUE<1 then error('registry/heldout mismatch '..total) end; "
        "if not CityManager.TransferCity then error('GameCore TransferCity unavailable') end; "
        "return 'registered='..total..' queued='..#JAC_UNIFY_QUEUE..' Ainu held out'"
    )
    chunk = (
        "for i=1,5 do if #JAC_UNIFY_QUEUE==0 then break end; "
        "local row=table.remove(JAC_UNIFY_QUEUE); local city=CityManager.GetCity(row.owner,row.id); "
        "if not city then error('castle missing '..row.owner..':'..row.id) end; "
        "CityManager.TransferCity(city,0) end; "
        "return #JAC_UNIFY_QUEUE"
    )
    negative = (
        f"local marker=GameInfo.Buildings['{marker}'].Index; local human=0; "
        "local total=0; local owned=0; for _,owner in ipairs(PlayerManager.GetAliveIDs()) do "
        "local player=Players[owner]; if player and player:IsMajor() then "
        "for _,city in player:GetCities():Members() do if city:GetBuildings():HasBuilding(marker) then "
        "total=total+1; if owner==human then owned=owned+1 end end end end end; "
        f"if total~={count} or owned~={count - 1} then error('negative count '..owned..'/'..total) end; "
        "if Game.GetWinningTeam()~=nil then error('victory with one castle missing') end; "
        "return 'negative: one Ainu castle missing; no winner'"
    )
    final = (
        f"local marker=GameInfo.Buildings['{marker}'].Index; local human=Game.GetLocalPlayer(); "
        "local ainu=nil; for _,owner in ipairs(PlayerManager.GetAliveIDs()) do "
        "if PlayerConfigurations[owner]:GetCivilizationTypeName()=='CIVILIZATION_JAC_AINU' then "
        "for _,city in Players[owner]:GetCities():Members() do "
        "if city:GetBuildings():HasBuilding(marker) then "
        "if ainu then error('multiple held out Ainu castles') end; ainu=city end end end end; "
        "if not ainu then error('Ainu held out castle missing') end; "
        "CityManager.TransferCity(ainu,human); "
        f"local owned=0; for _,city in Players[human]:GetCities():Members() do if city:GetBuildings():HasBuilding(marker) then owned=owned+1 end end; if owned~={count} then error('positive count '..owned) end; "
        "return 'positive: all registered castles transferred'"
    )
    return {
        "name": "Sengoku unification victory: one castle missing, save/load, then all castles",
        "judge_profile": "generic",
        "steps": [
            base["steps"][0], base["steps"][1], setup["steps"][2],
            {"action": "start_game", "timeout": 600},
            {"action": "ui_lua", "state_name": "GameCore_Tuner", "code": initial},
            *({"action": "ui_lua", "state_name": "GameCore_Tuner", "code": chunk} for _ in range((count + 4) // 5)),
            {"action": "ui_lua", "state_name": "GameCore_Tuner", "code":
             "if #JAC_UNIFY_QUEUE~=0 then error('transfer queue not empty '..#JAC_UNIFY_QUEUE) end; return true"},
            {"action": "ui_lua", "state_name": "InGame", "code": negative},
            {"action": "ui_lua", "state_name": "InGame", "code":
             "LuaEvents.PartialScreenHooks_OpenWorldRankings(); return true"},
            {"action": "wait_for", "condition": {"type": "lua", "state_name": "WorldRankings", "code":
             "return not ContextPtr:IsHidden()"}, "timeout": 30},
            {"action": "ui_lua", "state_name": "WorldRankings", "code":
             f"if not GameInfo.Victories['{victory}'] then error('victory absent from rankings') end; "
             f"ViewGeneric('{victory}'); if Controls.GenericView:IsHidden() then error('custom victory tab hidden') end; "
             "return 'World Rankings shows 天下統一 condition'"},
            {"action": "screenshot", "path": "unification-progress-negative.png"},
            {"action": "ui_lua", "state_name": "InGame", "code":
             "LuaEvents.PartialScreenHooks_CloseAllExcept('_AllTheThings'); return true"},
            {"action": "end_turn", "timeout": 180},
            {"action": "ui_lua", "state_name": "InGame", "code": negative},
            {"action": "save", "name": "jac-unification-negative"},
            {"action": "load", "name": "jac-unification-negative", "timeout": 600},
            {"action": "ui_lua", "state_name": "InGame", "code": negative},
            {"action": "ui_lua", "state_name": "GameCore_Tuner", "code": final},
            {"action": "wait_for", "condition": {"type": "lua", "state_name": "InGame", "code":
             "local winner,v=Game.GetWinningTeam(); "
             "if winner==nil and not JAC_UNIFY_END_REQUESTED then JAC_UNIFY_END_REQUESTED=true; "
             "UI.RequestAction(ActionTypes.ACTION_ENDTURN) end; "
             f"return winner==Players[Game.GetLocalPlayer()]:GetTeam() and v~=nil and GameInfo.Victories[v] and GameInfo.Victories[v].VictoryType=='{victory}'"},
             "timeout": 60},
            {"action": "ui_lua", "state_name": "InGame", "code":
             f"local winner,v=Game.GetWinningTeam(); if winner~=Players[Game.GetLocalPlayer()]:GetTeam() or not GameInfo.Victories[v] or GameInfo.Victories[v].VictoryType~='{victory}' then error('wrong winner '..tostring(winner)..'/'..tostring(v)) end; return '天下統一 fired for human'"},
        ],
    }


if __name__ == "__main__":
    main()
