def _base() -> tuple[dict, dict]:
    base = json.loads((SCENARIOS / "japan-map-15km.json").read_text(encoding="utf-8"))
    setup = json.loads((SCENARIOS / "sengoku-trees.json").read_text(encoding="utf-8"))
    return base, setup


def _setup_step(setup: dict, second_leader: str) -> dict:
    step = dict(setup["steps"][2])
    step["code"] = step["code"].replace("LEADER_JAC_TAKEDA_NOBUTORA", second_leader)
    return step


HUMAN = 0  # configure puts the human Oda in slot 0 (checked by the HostGame step)


def _castle_lua(rows: list[tuple[int, int, int]]) -> str:
    """Lua prelude: castle(city) is true for a city standing on a registered plot."""
    keys = ",".join(f"['{x},{y}']=true" for x, y, _ in rows)
    return (f"local plots={{{keys}}}; "
            "local function castle(city) return plots[city:GetX()..','..city:GetY()]==true end; ")


def _razed_lua(rows: list[tuple[int, int, int]]) -> str:
    """GameCore prelude: registered coordinates, the rebuilt marker, and the script's razed record."""
    coords = ",".join(f"{{{x},{y}}}" for x, y, _ in rows)
    return (f"local coords={{{coords}}}; local marker=GameInfo.Buildings['{REBUILT}'].Index; "
            f"local function razed(x,y) return Game:GetProperty('{RAZED_PREFIX}'..Map.GetPlot(x,y):GetIndex())==true end; ")


def _player_lua(var: str, civ: str, label: str) -> str:
    """Lua prelude: `var` is the slot of `civ`, dead or alive (a player losing its last city leaves
    GetAliveIDs; unification-alliance-01 2026-09-29). Every slot that ever lived, as the official
    Base/Assets/UI/ARXManager.lua:32 and Base/Assets/Maps/Utility/MapUtilities.lua:705 loop."""
    return (f"local {var}=nil; for id=0,PlayerManager.GetWasEverAliveCount()-1 do "
            f"if PlayerConfigurations[id]:GetCivilizationTypeName()=='{civ}' then {var}=id end end; "
            f"if not {var} then error('{label} missing') end; ")


def _tally() -> str:
    return ("local total=0; local owned=0; "
            "for _,owner in ipairs(PlayerManager.GetAliveIDs()) do "
            "for _,city in Players[owner]:GetCities():Members() do "
            "if castle(city) then total=total+1; "
            f"if owner=={HUMAN} then owned=owned+1 end end end end; ")


def _count_code(label: str, rows: list[tuple[int, int, int]], *,
                total: int | None = None, missing: int | None = None) -> str:
    """Count cities on registered plots over every alive player (majors, minors, free cities)."""
    checks = [f"total~={total}"] if total is not None else []
    checks += [f"total-owned~={missing}"] if missing is not None else []
    return (_castle_lua(rows) + _tally() +
            f"if {' or '.join(checks)} then error('{label} castles '..owned..'/'..total) end; ")


def scenario() -> dict:
    """Live check on the small test map; no mass transfers (live stall 2026-09-29)."""
    base, setup = _base()
    rows = castles(TEST_MAP)
    total = len(rows)
    if not (total >= 3 and sum(owner == HUMAN for *_, owner in rows) == total - 2):
        raise ValueError(f"Test map must leave exactly two castles to Date: {rows}")
    players = [{"leader": test_map.SEATS[test_map.SEAT_INDEX[slug]].leader,
                "civ": test_map.SEATS[test_map.SEAT_INDEX[slug]].civ, "human": slug == "ODA"}
               for slug in test_map.PLAYERS]
    initial = (
        _count_code("initial", rows, total=total, missing=2) +
        f"if not Game.IsVictoryEnabled('{VICTORY}') then error('unification victory disabled') end; "
        "if Game.GetWinningTeam()~=nil then error('winner at start') end; "
        f"return 'registered={total}, two held by Date'"
    )
    # Raze Date's non-capital castle so the condition must shrink to the survivors.
    # DestroyCity is only a GameCore export string (worked live 2026-09-29); if it does not
    # remove the city, hand the city to Oda instead and let the rebuild step fail (no razed plot).
    raze = (
        _castle_lua(rows) + _player_lua("date", players[1]["civ"], "Date") + "local target=nil; "
        "local capital=Players[date]:GetCities():GetCapitalCity(); "
        "for _,city in Players[date]:GetCities():Members() do "
        "if castle(city) and (not capital or city:GetID()~=capital:GetID()) "
        "then target=city end end; "
        "if not target then error('Date castle to raze missing') end; "
        "local owner,id=target:GetOwner(),target:GetID(); local how='DestroyCity'; "
        "if CityManager.DestroyCity then pcall(CityManager.DestroyCity,target) end; "
        "if CityManager.GetCity(owner,id) then how='fallback transfer (DestroyCity did not raze)'; "
        f"CityManager.TransferCity(CityManager.GetCity(owner,id),{HUMAN}) end; "
        "return 'raze: '..how"
    )
    negative = (
        _count_code("negative", rows, missing=1) +
        "if Game.GetWinningTeam()~=nil then error('victory with one castle missing') end; "
        "return 'negative: one castle missing ('..owned..'/'..total..'); no winner'"
    )
    # The turn-start scan (JAC_Sengoku_RebuiltCastles.lua) recorded the razed plot before the save.
    # Found a city there for Ashina the way the official Tuner places cities
    # (Players[p]:GetCities():Create(x, y), Base/Assets/UI/Tuner/TunerMapPanel.lua:119).
    rebuild = (
        _razed_lua(rows) + "local target=nil; "
        "for _,xy in ipairs(coords) do local city=CityManager.GetCityAt(xy[1],xy[2]); "
        "if razed(xy[1],xy[2]) then if city then error('razed plot has a city') end; "
        "if target then error('more than one razed plot') end; target=xy "
        "elseif not city then error('empty plot not recorded as razed: '..xy[1]..','..xy[2]) end end; "
        "if not target then error('no razed plot recorded (raze or turn-start scan failed)') end; "
        + _player_lua("builder", players[2]["civ"], "Ashina") +
        "Players[builder]:GetCities():Create(target[1],target[2]); "
        "if not CityManager.GetCityAt(target[1],target[2]) then error('rebuild failed') end; "
        "return 'rebuilt '..target[1]..','..target[2]..' for Ashina'"
    )
    # After a turn start the rebuilt city holds the marker; the original castles never do.
    rebuilt = (
        _razed_lua(rows) + "local n=0; "
        "for _,xy in ipairs(coords) do local city=CityManager.GetCityAt(xy[1],xy[2]); "
        "if city and razed(xy[1],xy[2]) then n=n+1; "
        "if not city:GetBuildings():HasBuilding(marker) then error('rebuilt city unmarked') end "
        "elseif city and city:GetBuildings():HasBuilding(marker) then error('original castle marked') end end; "
        "if n~=1 then error('rebuilt cities '..n) end; "
        "if Game.GetWinningTeam()~=nil then error('winner before the last castle') end; "
        "return 'rebuilt city marked; no winner'"
    )
    final = (
        _castle_lua(rows) + _player_lua("date", players[1]["civ"], "Date") + "local last=nil; "
        "for _,city in Players[date]:GetCities():Members() do "
        "if castle(city) then "
        "if last then error('more than one castle held out') end; last=city end end; "
        "if not last then error('held out castle missing') end; "
        f"CityManager.TransferCity(last,{HUMAN}); return 'transferred the last castle'"
    )
    won = (
        "local winner,v=Game.GetWinningTeam(); "
        f"return winner==Players[{HUMAN}]:GetTeam() and v~=nil and GameInfo.Victories[v]~=nil "
        f"and GameInfo.Victories[v].VictoryType=='{VICTORY}'"
    )
    # Checked in GameCore: the game ends on the transfer and InGame kept showing "2/3" afterwards
    # (live 2026-09-29, unify-08/11/12/13). GameEvents.CityBuilt fires on TransferCity (unify-13),
    # so the transferred castle must stay unmarked.
