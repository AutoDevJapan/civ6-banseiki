def castles(path: Path) -> list[tuple[int, int, int]]:
    """(x, y, map owner ID) of every preplaced city, in plot order."""
    with closing(sqlite3.connect(path)) as db:
        width = db.execute("SELECT Width FROM Map").fetchone()[0]
        rows = db.execute("SELECT Plot, Owner FROM Cities ORDER BY Plot").fetchall()
    if not rows:
        raise ValueError(f"No registered castles: {path}")
    return [(plot % width, plot // width, owner) for plot, owner in rows]


def verify_registry() -> int:
    """Both historical maps register the same number of castles; settler maps none."""
    manifest = json.loads((MAP_MOD / "Maps/manifest.json").read_text(encoding="utf-8"))
    counts = {len(castles(MAP_MOD / "Maps" / item["file"])) for item in manifest}
    for item in manifest:
        with closing(sqlite3.connect(MAP_MOD / "Maps" / item["settler_file"])) as db:
            if db.execute("SELECT COUNT(*) FROM Cities").fetchone()[0]:
                raise ValueError(f"Settler map has registered castles: {item['settler_file']}")
    if len(counts) != 1:
        raise ValueError(f"Historical maps have different castle counts: {counts}")
    return counts.pop()


def castle_sql(tag: str, rows: list[tuple[int, int, int]]) -> str:
    ids = [f"JAC_UNIFICATION_CASTLE_{tag}_{x}_{y}" for x, y, _ in rows]
    join = ",\n    ".join
    args = join(f"('{rid}', '{name}', '{value}')" for rid, (x, y, _) in zip(ids, rows)
                for name, value in (("X", x), ("Y", y)))
    return f"""-- Generated by tools/generate_unification_victory.py from this map's Cities rows.
-- A city standing on one of these plots is a registered castle, whoever owns it.
-- Loaded after the victory SQL (LoadOrder 300); OR IGNORE keeps the shared set either way.
INSERT OR IGNORE INTO RequirementSets (RequirementSetId, RequirementSetType) VALUES
    ('{CASTLE_SET}', 'REQUIREMENTSET_TEST_ANY');
INSERT INTO Requirements (RequirementId, RequirementType) VALUES
    {join(f"('{rid}', 'REQUIREMENT_CITY_LOCATION_MATCHES')" for rid in ids)};
INSERT INTO RequirementArguments (RequirementId, Name, Value) VALUES
    {args};
INSERT INTO RequirementSetRequirements (RequirementSetId, RequirementId) VALUES
    {join(f"('{CASTLE_SET}', '{rid}')" for rid in ids)};
"""


