"""Generate the Sengoku unification victory SQL, castle registries, test map and live scenarios.

A registered castle is a city-centre plot of a historical-start map (its Cities
rows). The victory checks the city standing on each such plot with the official
REQUIREMENT_CITY_LOCATION_MATCHES (DLC/WarMachineScenario/Data/
WarMachineScenario_GameplayData.xml:443,450-451), so capture or transfer keeps the
castle counted. A marker building would not survive: the city centre district has
CaptureRemovesBuildings (Base/Assets/Gameplay/Data/Districts.xml:43).
A team wins when it holds every city standing on a registered plot. A razed castle
drops out (owner decision 3a, SSOT 3.1): a city later founded on its plot gets the
hidden BUILDING_JAC_REBUILT_ON_CASTLE from Scripts/JAC_Sengoku_RebuiltCastles.lua
and is excluded. Maps without registered castles
(settler starts, ordinary maps) use the official domination rule: every original
capital (SSOT 3.1).
A 天下統一同盟 (unification pact, SSOT 3.1) and a 1534 start alliance pool castles across teams
(on maps without counted castles: every major's home capital, owner decision O-8): once the
group's teams hold every target, Scripts/JAC_Sengoku_UnificationPact.lua puts the hidden
BUILDING_JAC_PACT_UNIFIED in the lead's capital, and the pact branch lets only the team
owning that city (the lead's) win. The branch does not depend on the map kind.
"""

