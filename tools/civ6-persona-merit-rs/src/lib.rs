//! Event-time merit policy. Rust is the source; Civ6's Lua 5.1 adapter is
//! generated from the same guards and expressions tested below.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Capture {
    pub eligible: bool,
    pub count: u32,
    pub cap: u32,
    pub reward: u32,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Reservation {
    pub amount: u32,
    pub count: u32,
}

impl Capture {
    pub fn reserve(self) -> Option<Reservation> {
        if !self.eligible || self.cap == 0 || self.reward == 0 {
            return None;
        }
        let paid = self.count < self.cap;
        Some(Reservation {
            amount: if paid { self.reward } else { 0 },
            count: if paid { self.count + 1 } else { self.cap },
        })
    }
}

/// Serialized qualified entries have their own version and explicit proof.
/// In particular, neither a missing flag nor a legacy unknown entry qualifies.
pub const VERSION: u32 = 2;

/// The adapter only marshals synchronized Game properties. It never calls a
/// UI reader, asks for current placement to reinterpret history, or runs an
/// external worker. Capture reserves the ORIGINAL turn's cap before any later
/// notification; drain orders immutable entries and commits them once.
pub fn adapter() -> String {
    format!(
        r#"-- Generated by civ6-persona-merit-rs; edit its Rust source.
JAC_PersonaMeritQueue = {{}}
local Q = JAC_PersonaMeritQueue
local PENDING = 'JAC_PERSONA_PENDING_DEEDS'
local BUCKETS = 'JAC_PERSONA_MERIT_BUCKETS_V2'
local function integer(value)
    return type(value) == 'number' and value >= 0 and value < 9007199254740992 and value % 1 == 0
end
function Q.Reserve(eligible, count, cap, reward)
    if eligible ~= true or not integer(count) or not integer(cap) or not integer(reward) or cap <= 0 or reward <= 0 then return nil end
    if count < cap then return reward, count + 1 end
    return 0, cap
end
function Q.Capture(row, deed, identity, city, a)
    local leader = row.LeaderType
    local owner = a.Get(leader, 'OWNER')
    local key = leader .. '_' .. deed .. '_' .. identity
    local pending = Game:GetProperty(PENDING)
    if pending == nil then pending = {{}} end
    if type(pending) ~= 'table' then return false end
    if pending[key] or a.Get(leader, 'DEED_' .. deed .. '_' .. identity) ~= nil then return false end
    if not city or not a.Player(owner, true) or city:GetOwner() ~= owner then return false end
    local turn = Game.GetCurrentGameTurn()
    local cap = deed == 'GOVERN_TURN' and 1 or a.Parameter(deed .. '_DEEDS_PER_TURN')
    local reward = GameInfo.JAC_PersonaMeritRules[GameInfo.JAC_PersonaTreePeople[leader].MeritProfile][deed]
    local buckets = Game:GetProperty(BUCKETS)
    if buckets == nil then buckets = {{}} end
    if type(buckets) ~= 'table' then return false end
    local bucket = leader .. '_' .. deed .. '_' .. turn
    local count = buckets[bucket]
    if count == nil then count = a.Get(leader, deed .. '_COUNT_TURN') == turn and (a.Get(leader, deed .. '_COUNT') or 0) or 0 end
    local amount, reserved = Q.Reserve(true, count, cap, reward)
    if amount == nil then return false end
    local priorSequence = Game:GetProperty('JAC_PERSONA_PENDING_SEQUENCE')
    if priorSequence == nil then priorSequence = 0 end
    if not integer(priorSequence) or priorSequence >= 9007199254740991 then return false end
    local sequence = priorSequence + 1
    pending[key] = {{version={version}, leader=leader, owner=owner, deed=deed,
        identity=identity, turn=turn, sequence=sequence, cityID=city:GetID(),
        eligibilityUnknown=false, eligible=true, amount=amount, reservedCount=reserved,
        cap=cap, reward=reward}}
    buckets[bucket] = reserved
    Game:SetProperty(BUCKETS, buckets)
    Game:SetProperty('JAC_PERSONA_PENDING_SEQUENCE', sequence)
    Game:SetProperty(PENDING, pending)
    return amount > 0
end
function Q.Drain(a)
    local pending = Game:GetProperty(PENDING)
    local buckets = Game:GetProperty(BUCKETS)
    if pending == nil then pending = {{}} end
    if buckets == nil then buckets = {{}} end
    if type(pending) ~= 'table' or type(buckets) ~= 'table' then return end
    local changed = false
    local completedBuckets = {{}}
    local ordered = {{}}
    for key, event in pairs(pending) do
        if type(event) == 'table' and event.version == {version} and event.eligible == true and
           event.eligibilityUnknown == false and integer(event.sequence) and event.sequence > 0 then
            ordered[#ordered + 1] = {{key=key, event=event}}
        end
    end
    table.sort(ordered, function(x,y)
        if x.event.sequence ~= y.event.sequence then return x.event.sequence < y.event.sequence end
        return tostring(x.key) < tostring(y.key)
    end)
    local sequenceSeen = {{}}
    for _, item in ipairs(ordered) do
        local e, key = item.event, item.key
        -- A duplicate sequence is ambiguous, so reject all members of it.
        sequenceSeen[e.sequence] = (sequenceSeen[e.sequence] or 0) + 1
    end
    for _, item in ipairs(ordered) do
        local e, key = item.event, item.key
        local row = type(e.leader) == 'string' and GameInfo.JAC_LeaderPersonas[e.leader]
        local known = e.deed == 'GOVERN_TURN' or e.deed == 'BUILDING' or e.deed == 'VICTORY' or e.deed == 'ALLIANCE'
        if row and known and type(e.identity) == 'string' and integer(e.owner) and integer(e.turn) and
           integer(e.cityID) and integer(e.amount) and integer(e.reservedCount) and sequenceSeen[e.sequence] == 1 and
           key == e.leader .. '_' .. e.deed .. '_' .. e.identity and e.turn <= Game.GetCurrentGameTurn() and
           a.Get(e.leader, 'OWNER') == e.owner and a.Player(e.owner, true) then
            -- These are event-time rule values. A later balance update must
            -- neither strand a proven event nor change its committed amount.
            local cap, reward = e.cap, e.reward
            local bucket = e.leader .. '_' .. e.deed .. '_' .. e.turn
            local reserved = buckets[bucket]
            if integer(cap) and cap > 0 and integer(reward) and reward > 0 and
               e.reservedCount > 0 and e.reservedCount <= cap and integer(reserved) and reserved >= e.reservedCount and reserved <= cap and
               (e.amount == reward or (e.amount == 0 and e.reservedCount == cap)) then
                local seen = 'DEED_' .. e.deed .. '_' .. e.identity
                if a.Get(e.leader, seen) == nil then
                    -- No save or other callback can run inside this synchronous
                    -- Gameplay commit. Mark a receipt before callback-visible work.
                    a.Set(e.leader, seen, e.turn)
                    a.Set(e.leader, 'MERIT', a.Merit(e.leader) + e.amount)
                    local priorTurn = a.Get(e.leader, e.deed .. '_COUNT_TURN')
                    if priorTurn == nil or priorTurn <= e.turn then
                        local oldCount = priorTurn == e.turn and (a.Get(e.leader, e.deed .. '_COUNT') or 0) or 0
                        a.Set(e.leader, e.deed .. '_COUNT_TURN', e.turn)
                        a.Set(e.leader, e.deed .. '_COUNT', math.max(oldCount, e.reservedCount))
                    end
                end
                pending[key] = nil
                changed = true
                completedBuckets[bucket] = true
            end
        end
    end
    if changed then
        -- Once all qualified entries for a turn are committed, ordinary saved
        -- counters and receipts suffice. Keep buckets only for unresolved work.
        for _,e in pairs(pending) do
            if type(e) == 'table' and type(e.leader) == 'string' and type(e.deed) == 'string' and integer(e.turn) then
                completedBuckets[e.leader .. '_' .. e.deed .. '_' .. e.turn] = nil
            end
        end
        for bucket in pairs(completedBuckets) do buckets[bucket] = nil end
        Game:SetProperty(BUCKETS, next(buckets) and buckets or nil)
        Game:SetProperty(PENDING, next(pending) and pending or nil)
    end
end
"#,
        version = VERSION,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn malformed_saved_queue_or_counters_do_not_throw_or_award() {
        let lua = mlua::Lua::new();
        lua.load(adapter()).exec().unwrap();
        lua.load(r#"
            local q=JAC_PersonaMeritQueue
            local pending,buckets,sequence
            Game={GetProperty=function(_,key)
                if key=='JAC_PERSONA_PENDING_DEEDS' then return pending end
                if key=='JAC_PERSONA_MERIT_BUCKETS_V2' then return buckets end
                if key=='JAC_PERSONA_PENDING_SEQUENCE' then return sequence end
            end,GetCurrentGameTurn=function() return 1 end,
                SetProperty=function() error('malformed capture modified saved data') end}
            GameInfo={JAC_PersonaTreePeople={L={MeritProfile='P'}},JAC_PersonaMeritRules={P={BUILDING=3}}}
            local a={Get=function(_,f) if f=='OWNER' then return 0 end end,
                Player=function() return true end,Parameter=function() return 2 end,
                Merit=function() return 0 end,Set=function() error('unexpected award') end}
            local city={GetID=function() return 1 end,GetOwner=function() return 0 end}
            for _,value in ipairs({false,1,'invalid'}) do
                pending=value; buckets=nil; q.Drain(a)
                assert(q.Capture({LeaderType='L'},'BUILDING','one',city,a)==false)
                pending=nil; buckets=value; q.Drain(a)
                assert(q.Capture({LeaderType='L'},'BUILDING','one',city,a)==false)
                buckets=nil; sequence=value
                if value=='invalid' or value==false then assert(q.Capture({LeaderType='L'},'BUILDING','one',city,a)==false) end
            end
            sequence=9007199254740991
            assert(q.Capture({LeaderType='L'},'BUILDING','one',city,a)==false)
            assert(q.Reserve(true,'bad',2,3)==nil)
            assert(q.Reserve(true,0,'bad',3)==nil)
            assert(q.Reserve(true,0,2,'bad')==nil)
        "#).exec().unwrap();
    }

    #[test]
    fn reservation_keeps_original_turn_cap() {
        assert_eq!(
            Capture {
                eligible: true,
                count: 0,
                cap: 2,
                reward: 3
            }
            .reserve(),
            Some(Reservation {
                amount: 3,
                count: 1
            })
        );
        assert_eq!(
            Capture {
                eligible: true,
                count: 2,
                cap: 2,
                reward: 3
            }
            .reserve(),
            Some(Reservation {
                amount: 0,
                count: 2
            })
        );
        assert_eq!(
            Capture {
                eligible: false,
                count: 0,
                cap: 2,
                reward: 3
            }
            .reserve(),
            None
        );
    }

    #[test]
    fn emitted_lua51_reservation_matches_rust_for_all_small_inputs() {
        let lua = mlua::Lua::new();
        lua.load(adapter()).exec().unwrap();
        let q: mlua::Table = lua.globals().get("JAC_PersonaMeritQueue").unwrap();
        let f: mlua::Function = q.get("Reserve").unwrap();
        for eligible in [false, true] {
            for count in 0..5 {
                for cap in 0..4 {
                    for reward in 0..10 {
                        let got: (Option<u32>, Option<u32>) =
                            f.call((eligible, count, cap, reward)).unwrap();
                        let want = Capture {
                            eligible,
                            count,
                            cap,
                            reward,
                        }
                        .reserve();
                        assert_eq!(
                            got,
                            want.map(|x| (Some(x.amount), Some(x.count)))
                                .unwrap_or((None, None))
                        );
                    }
                }
            }
        }
    }
}
